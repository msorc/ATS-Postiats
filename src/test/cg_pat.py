CONS = [('P2TCany', []), ('P2TCcon', ['d2con', 'p2atcstlst']), ('P2TCempty', []), ('P2TCint', ['intinf']), ('P2TCintc', ['intinfset']),
        ('P2TCbool', ['bool']), ('P2TCchar', ['char']), ('P2TCcharc', ['charset']), ('P2TCfloat', ['string']), ('P2TCstring', ['string']),
        ('P2TCrec', ['int', 'labp2atcstlst'])]

def gen_compat(lang):
    o = ['(* generated by cg_gen.py (%s): wrappers of the constructors of pats_patcst2.spec and the typed lists *)' % ('ATS1' if lang == 1 else 'ATS2')]
    for c, ts in CONS:
        params = ', '.join('a%d: %s' % (i, t) for i, t in enumerate(ts))
        args = ', '.join('a%d' % i for i in range(len(ts)))
        if lang == 1:
            o.append('fun K_%s (%s): p2atcst = %s (%s)' % (c, params, c, args))
        else:
            o.append('fun K_%s (%s): p2atcst = p2atcst_%s (%s)' % (c, params, c, args))
    if lang == 1:
        o.append('fun K_LABP2ATCST (l: label, x: p2atcst): labp2atcst = LABP2ATCST (l, x)')
    else:
        o.append('fun K_LABP2ATCST (l: label, x: p2atcst): labp2atcst = labp2atcst_new (l, x)')
    for a, e in (('p2atcstlst', 'p2atcst'), ('labp2atcstlst', 'labp2atcst'), ('p2atcstlstlst', 'p2atcstlst')):
        if lang == 1:
            o.append('fun LN_%s (): %s = list_nil ()' % (a, a))
            o.append('fun LC_%s (x: %s, xs: %s): %s = list_cons (x, xs)' % (a, e, a, a))
        else:
            o.append('fun LN_%s (): %s = glist_nil ()' % (a, a))
            o.append('fun LC_%s (x: %s, xs: %s): %s = glist_cons<%s> (x, xs)' % (a, e, a, a, e))
    return '\n'.join(o) + '\n'

