# the cases of pats_patcst2 (called by cg_cases.py, see there and PORTING.md, "Pattern coverage (patcst2)")
#
# The patterns: a universe of datatypes (the constructors have argument types: int, bool, char, string, a datatype, a list, a tuple), random patterns of
# a given type (with wildcards, variables, as-patterns, existentials, annotations, literals with suffixes, lists, records with permuted or omitted
# labels), converted to constraints (p2at2cst), complemented (p2atcst_comp), compared (inter_test, diff) and run through the case-checking loop of
# pats_trans3_caseof.dats (cg_sim_* of cgcommon.hats). The constraints are also built directly (every constructor, the sets of integers and of characters).
import sys
