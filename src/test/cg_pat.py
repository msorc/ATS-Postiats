BASE = ['int', 'bool', 'char', 'string', 'float', 'unit']

def rand_type(R, ndt, d):
    r = R.random()
    if d <= 0 or r < 0.5:
        if ndt and R.random() < 0.5: return ('dt', R.randrange(ndt))
        return (R.choice(BASE),)
    if r < 0.7: return ('list', rand_type(R, ndt, d - 1))
    if r < 0.85: return ('tup', [rand_type(R, ndt, d - 1) for _ in range(R.choice([2, 2, 3]))])
    if r < 0.95: return ('rec', [rand_type(R, ndt, d - 1) for _ in range(R.choice([1, 2, 3]))])
    return ('dt', R.randrange(ndt)) if ndt else ('int',)

class Uni:
    """the datatypes of a scenario: for each, the constructors (name, the types of the arguments, npf, tag) and the handles"""
    def __init__(self, sc, ndt):
        R = sc.R
        self.sc = sc
        self.dts = []
        for i in range(ndt):
            ncon = R.choice([1, 2, 2, 3, 3, 4])
            cons = []
            for j, nm in enumerate(R.sample(CON_NAMES, ncon)):
                nargs = R.choice([0, 1, 1, 2, 2, 3])
                tys = [rand_type(R, ndt, 1) for _ in range(nargs)]
                tag = j if R.random() < 0.93 else -1
                cons.append([nm, tys, 0, tag])
            self.dts.append(cons)
        self.cells = []
        for i, cons in enumerate(self.dts):
            c, ds = mk_dat(sc, 'dat%d' % i, [(nm, len(tys), npf, tag) for nm, tys, npf, tag in cons])
            self.cells.append((c, ds))
        self.dv = sc.val('d2var_make (%s, %s)' % (LOC(sc), S('x')), 'd2var')
        self.sv = sc.val('s2var_make_srt (s2rt_type)', 's2var')

def lab_of(i, named):
    return '$LAB.label_make_int (%d)' % i if not named else '$LAB.label_make_string ("l%d")' % i

def gen_pat(sc, U, ty, d, chaos=0.0, top=False):
    """a pattern (an expression of type p2at) for the type ty"""
    R = sc.R
    loc = LOC(sc)
    r = R.random()
    if chaos and R.random() < chaos:
        ty = rand_type(R, len(U.dts), 1)
    wild = 0.04 if top else 0.14
    if r < wild or d < -1:
        return 'p2at_any (%s)' % loc
    if r < 2 * wild:
        return 'p2at_var (%s, %s)' % (loc, U.dv)
    if d > 0 and r < 2 * wild + 0.06:
        inner = gen_pat(sc, U, ty, d - 1, chaos)
        w = R.choice(['refas', 'exist', 'ann', 'refas2'])
        if w == 'refas' or w == 'refas2': return 'p2at_refas (%s, %s, %s)' % (loc, U.dv, inner)
        if w == 'exist': return 'p2at_exist (%s, %s, %s)' % (loc, sc.lst('s2varlst', [U.sv]), inner)
        return 'p2at_ann (%s, %s, s2exp_int (0))' % (loc, inner)
    if r < 2 * wild + 0.08:
        return 'p2at_vbox (%s, %s)' % (loc, U.dv)
    k = ty[0]
    if k == 'int':
        c = R.choice(['int', 'int', 'int', 'rep', 'i0nt'])
        if c == 'int': return 'p2at_int (%s, %d)' % (loc, R.choice([0, 1, 2, 3, 3, 4, 100, -5]))
        if c == 'rep': return 'p2at_intrep (%s, "%s")' % (loc, R.choice(['0', '1', '2', '42', '99999999999999999999', '-7']))
        return 'p2at_i0nt (%s, token_make (%s, mktnode_int_sfx (%d)))' % (loc, loc, R.randint(0, 2)) if R.random() < 0.6 else 'p2at_i0nt (%s, mki0nt (%d))' % (loc, R.randint(0, 5))
    if k == 'bool': return 'p2at_bool (%s, %s)' % (loc, R.choice(['true', 'false']))
    if k == 'char': return "p2at_char (%s, %s)" % (loc, R.choice(["'a'", "'b'", "'c'", "'a'", "'\\n'", "'Z'"]))
    if k == 'string': return 'p2at_string (%s, "%s")' % (loc, R.choice(['', 'a', 'b', 'abc', 'a\\"b', 'a']))
    if k == 'float':
        if R.random() < 0.7: return 'p2at_float (%s, "%s")' % (loc, R.choice(['1.0', '2.5', '1.0', '3e4']))
        return 'p2at_f0loat (%s, mkf0loat (%d))' % (loc, R.randint(0, 3))
    if k == 'unit': return 'p2at_empty (%s)' % loc
    if k == 'dt':
        cons = U.dts[ty[1]]
        j = R.randrange(len(cons))
        nm, tys, npf, tag = cons[j]
        ds = U.cells[ty[1]][1]
        args = [gen_pat(sc, U, t, d - 1, chaos) for t in tys]
        if R.random() < 0.04 and args: args = args[:-1]
        if R.random() < 0.03: args = args + [gen_pat(sc, U, ('int',), 0)]
        return 'p2at_con (%s, mkpckind (%d), %s, LN_s2qualst (), s2exp_int (0), %d, %s)' % (loc, R.randint(0, 3), ds[j], R.choice([0, 0, 1]), sc.lst('p2atlst', args))
    if k == 'list':
        n = R.choice([0, 1, 2, 3])
        if d <= 0: n = R.choice([0, 1])
        if R.random() < 0.45:
            return 'p2at_lst (%s, %d, %s)' % (loc, R.choice([0, 1]), sc.lst('p2atlst', [gen_pat(sc, U, ty[1], d - 1, chaos) for _ in range(n)]))
        # cons / nil patterns
        if R.random() < 0.3:
            return 'p2at_con (%s, mkpckind (0), cg_lnil (), LN_s2qualst (), s2exp_int (0), 0, LN_p2atlst ())' % loc
        return 'p2at_con (%s, mkpckind (0), cg_lcons (), LN_s2qualst (), s2exp_int (0), 0, %s)' % (
            loc, sc.lst('p2atlst', [gen_pat(sc, U, ty[1], d - 1, chaos), gen_pat(sc, U, ty, d - 1, chaos)]))
    if k in ('tup', 'rec'):
        ts = ty[1]
        named = (k == 'rec')
        idx = list(range(len(ts)))
        if R.random() < 0.5: R.shuffle(idx)
        fl = []
        for i in idx:
            if R.random() < 0.12: fl.append('K_LABP2ATomit (%s)' % loc)
            else: fl.append('K_LABP2ATnorm (l0ab_make_label (%s, %s), %s)' % (loc, lab_of(i, named), gen_pat(sc, U, ts[i], d - 1, chaos)))
        if R.random() < 0.12 and idx:   # a duplicate label (with another pattern: the order of the equal labels matters)
            fl.append('K_LABP2ATnorm (l0ab_make_label (%s, %s), %s)' % (loc, lab_of(idx[0], named), gen_pat(sc, U, ts[idx[0]], d - 1, chaos)))
        if R.random() < 0.7:
            return 'p2at_rec (%s, %d, 0, %s)' % (loc, R.choice([0, 1, 2]), sc.lst('labp2atlst', fl))
        return 'p2at_rec (%s, %d, 0, p2atlst_tupize (%s))' % (loc, R.choice([0, 1]), sc.lst('p2atlst', [gen_pat(sc, U, t, d - 1, chaos) for t in ts]))
    return 'p2at_any (%s)' % loc

def mk_clause(sc, U, tys, d, guard=0.15, chaos=0.0):
    R = sc.R
    pats = [gen_pat(sc, U, t, d, chaos, top=True) for t in tys]
    gua = 'LN_gm2atlst ()'
    if R.random() < guard:
        gua = sc.lst('gm2atlst', ['K_gm2at (%s, d2exp_empty (%s), ON_p2atopt ())' % (LOC(sc), LOC(sc))])
    return sc.val('K_c2lau (%s, %s, %s, %d, %d, d2exp_empty (%s))' % (LOC(sc), sc.lst('p2atlst', pats), gua, R.choice([0, 1]), R.choice([0, 0, 1]), LOC(sc)), 'c2lau'), pats

def cover(sc, U, ty, d):
    """a list of patterns of the type ty that is (mostly) a cover of the type"""
    R = sc.R
    loc = LOC(sc)
    if d <= 0 or R.random() < 0.1: return ['p2at_any (%s)' % loc]
    k = ty[0]
    if k == 'bool': return ['p2at_bool (%s, true)' % loc, 'p2at_bool (%s, false)' % loc]
    if k == 'int':
        return ['p2at_int (%s, %d)' % (loc, i) for i in R.sample([0, 1, 2, 3], R.choice([1, 2, 3]))] + ['p2at_any (%s)' % loc]
    if k == 'char': return ["p2at_char (%s, 'a')" % loc, "p2at_char (%s, 'b')" % loc, 'p2at_var (%s, %s)' % (loc, U.dv)]
    if k == 'string': return ['p2at_string (%s, "a")' % loc, 'p2at_string (%s, "b")' % loc, 'p2at_any (%s)' % loc]
    if k == 'unit': return ['p2at_empty (%s)' % loc]
    if k == 'float': return ['p2at_float (%s, "1.0")' % loc, 'p2at_any (%s)' % loc]
    if k == 'dt':
        cons = U.dts[ty[1]]
        ds = U.cells[ty[1]][1]
        res = []
        for j, (nm, tys, npf, tag) in enumerate(cons):
            args = [R.choice(cover(sc, U, t, d - 1)) for t in tys]
            res.append('p2at_con (%s, mkpckind (0), %s, LN_s2qualst (), s2exp_int (0), 0, %s)' % (loc, ds[j], sc.lst('p2atlst', args)))
        return res
    if k == 'list':
        e = R.choice(cover(sc, U, ty[1], d - 1))
        res = ['p2at_con (%s, mkpckind (0), cg_lnil (), LN_s2qualst (), s2exp_int (0), 0, LN_p2atlst ())' % loc]
        if R.random() < 0.5:
            res.append('p2at_con (%s, mkpckind (0), cg_lcons (), LN_s2qualst (), s2exp_int (0), 0, %s)' % (loc, sc.lst('p2atlst', [e, 'p2at_any (%s)' % loc])))
        else:
            res.append('p2at_con (%s, mkpckind (0), cg_lcons (), LN_s2qualst (), s2exp_int (0), 0, %s)' % (loc, sc.lst('p2atlst', ['p2at_any (%s)' % loc, 'p2at_var (%s, %s)' % (loc, U.dv)])))
        return res
    if k in ('tup', 'rec'):
        ts = ty[1]
        named = (k == 'rec')
        res = []
        for _ in range(R.choice([1, 2, 3])):
            fl = ['K_LABP2ATnorm (l0ab_make_label (%s, %s), %s)' % (loc, lab_of(i, named), R.choice(cover(sc, U, ts[i], d - 1))) for i in range(len(ts))]
            res.append('p2at_rec (%s, %d, 0, %s)' % (loc, R.choice([0, 1]), sc.lst('labp2atlst', fl)))
        return res
    return ['p2at_any (%s)' % loc]

def fam_pat_cover(sc, k):
    """the clauses are a cover of the scrutinee in random order, with duplicates, a missing clause, a guard"""
    R = sc.R
    sc.do('cg_env_clear ()')
    U = Uni(sc, R.choice([1, 2, 3]))
    ncol = R.choice([1, 1, 2])
    tys = [rand_type(R, len(U.dts), 1) for _ in range(ncol)]
    cols = [cover(sc, U, t, 2) for t in tys]
    loc = LOC(sc)
    rows = []
    for p0 in cols[0]:
        rows.append([p0] + ['p2at_any (%s)' % loc if R.random() < 0.6 else R.choice(cols[i]) for i in range(1, ncol)])
    if ncol > 1:
        for i in range(1, ncol):
            for p in cols[i]:
                rows.append([R.choice(cols[0]) if R.random() < 0.5 else 'p2at_any (%s)' % loc for _ in range(i)] + [p] + ['p2at_any (%s)' % loc] * (ncol - i - 1))
    R.shuffle(rows)
    if R.random() < 0.75: rows.sort(key=lambda r: ''.join(r).count('p2at_any'))   # the general clauses last
    if R.random() < 0.4 and len(rows) > 1: rows.pop(R.randrange(len(rows)))
    if R.random() < 0.3: rows.append(R.choice(rows))
    rows = rows[:8]
    cl = []
    for pats in rows:
        gua = 'LN_gm2atlst ()'
        if R.random() < 0.12:
            gua = sc.lst('gm2atlst', ['K_gm2at (%s, d2exp_empty (%s), ON_p2atopt ())' % (LOC(sc), LOC(sc))])
        cl.append(sc.val('K_c2lau (%s, %s, %s, %d, %d, d2exp_empty (%s))' % (LOC(sc), sc.lst('p2atlst', pats), gua, R.choice([0, 1]), R.choice([0, 0, 1]), LOC(sc)), 'c2lau'))
    knd = R.choice([0, 1, 1, 2])
    sc.do('{ val s0 = cg_sim_first (%d, %s) %s val () = cg_sim_end (s%d) }' % (
        knd, cl[0], ' '.join('val s%d = cg_sim_next (%d, s%d, %s)' % (i + 1, knd, i, c) for i, c in enumerate(cl[1:])), len(cl) - 1))
    sc.say('-- end')

def fam_pat_case(sc, k):
    """the conversion of the patterns and the case-checking loop"""
    R = sc.R
    sc.do('cg_env_clear ()')
    U = Uni(sc, R.choice([1, 2, 3]))
    ncol = R.choice([1, 1, 1, 2])
    tys = [rand_type(R, len(U.dts), 2) for _ in range(ncol)]
    ncl = R.choice([2, 3, 4, 5, 6])
    clauses = []
    for i in range(ncl):
        clauses.append(mk_clause(sc, U, tys, R.choice([1, 2, 2, 3]), chaos=R.choice([0, 0, 0, 0.1])))
    if R.random() < 0.4:   # a wildcard clause that closes the case
        clauses.append(mk_clause(sc, U, [('int',)] * ncol, 0, guard=0.0, chaos=0.0))
    for c2l, pats in clauses:
        for p in pats:
            sc.do('(print_p2atcst (p2at2cst (%s)); print_newline ())' % p)
        sc.do('(print_p2atcstlst (p2at2cstlst (%s)); print_newline ())' % sc.lst('p2atlst', pats))
        sc.do('cg_pr_vtvt (p2atcstlst_comp (p2at2cstlst (%s)))' % sc.lst('p2atlst', pats))
    knd = R.choice([0, 1, 1, 2])
    cl = [c for c, p in clauses]
    sc.do('{ val s0 = cg_sim_first (%d, %s) %s val () = cg_sim_end (s%d) }' % (
        knd, cl[0], ' '.join('val s%d = cg_sim_next (%d, s%d, %s)' % (i + 1, knd, i, c) for i, c in enumerate(cl[1:])), len(cl) - 1))
    sc.say('-- end')

def gen_cst(sc, U, d, chaos=0.0):
    """a constraint (an expression of type p2atcst)"""
    R = sc.R
    r = R.random()
    if (d <= 0 and r < 0.3) or d < -1: return 'K_P2TCany ()'
    c = R.choice(['any', 'con', 'con', 'empty', 'int', 'intc', 'bool', 'char', 'charc', 'float', 'string', 'rec', 'rec', 'con', 'lstcon'])
    if c == 'any': return 'K_P2TCany ()'
    if c == 'empty': return 'K_P2TCempty ()'
    if c == 'int': return 'K_P2TCint (cg_inf (%d))' % R.choice([0, 1, 2, 3])
    if c == 'intc':
        s = 'cg_iset (%d)' % R.choice([0, 1, 2])
        for _ in range(R.choice([0, 1, 2])): s = 'cg_iset_add (%s, %d)' % (s, R.choice([0, 1, 2, 3, 4]))
        return 'K_P2TCintc (%s)' % s
    if c == 'bool': return 'K_P2TCbool (%s)' % R.choice(['true', 'false'])
    if c == 'char': return "K_P2TCchar (%s)" % R.choice(["'a'", "'b'", "'c'"])
    if c == 'charc':
        s = "cg_cset (%s)" % R.choice(["'a'", "'b'"])
        for _ in range(R.choice([0, 1, 2])): s = "cg_cset_add (%s, %s)" % (s, R.choice(["'a'", "'b'", "'c'", "'d'"]))
        return 'K_P2TCcharc (%s)' % s
    if c == 'float': return 'K_P2TCfloat ("%s")' % R.choice(['1.0', '2.0'])
    if c == 'string': return 'K_P2TCstring ("%s")' % R.choice(['a', 'b', ''])
    if c == 'rec':
        n = R.choice([0, 1, 2, 3])
        labs = sorted(R.sample(range(4), n))
        named = R.random() < 0.5
        fl = ['K_LABP2ATCST (%s, %s)' % (lab_of(i, named), gen_cst(sc, U, d - 1, chaos)) for i in labs]
        return 'K_P2TCrec (%d, %s)' % (R.choice([0, 1, 2]), sc.lst('labp2atcstlst', fl))
    if c == 'lstcon':
        d2c = 'cg_lnil ()' if R.random() < 0.4 else 'cg_lcons ()'
        n = 0 if d2c == 'cg_lnil ()' else 2
        return 'K_P2TCcon (%s, %s)' % (d2c, sc.lst('p2atcstlst', [gen_cst(sc, U, d - 1, chaos) for _ in range(n)]))
    i = R.randrange(len(U.dts))
    cons = U.dts[i]
    j = R.randrange(len(cons))
    nm, tys, npf, tag = cons[j]
    n = len(tys) if R.random() < 0.85 else R.choice([0, 1, 2])
    return 'K_P2TCcon (%s, %s)' % (U.cells[i][1][j], sc.lst('p2atcstlst', [gen_cst(sc, U, d - 1, chaos) for _ in range(n)]))

def fam_pat_cst(sc, k):
    """the constraints built directly: comp, inter_test, diff on constraints, lists of constraints, records"""
    R = sc.R
    sc.do('cg_env_clear ()')
    U = Uni(sc, R.choice([1, 2]))
    cs = [sc.val(gen_cst(sc, U, R.choice([1, 2, 2])), 'p2atcst') for _ in range(R.choice([5, 6, 7]))]
    for c in cs:
        sc.do('(print_p2atcst (%s); print_newline ())' % c)
        sc.do('(prerr_p2atcst (%s); prerr_newline ())' % c)
        sc.do('(fprint_p2atcst (dd_out, %s); dd_nl ())' % c)
        sc.do('cg_pr_vt (p2atcst_comp (%s))' % c)
    for i in range(len(cs)):
        for j in range(len(cs)):
            if R.random() < 0.55 or i == j:
                sc.do('(dd_bool (p2atcst_inter_test (%s, %s)); dd_nl ())' % (cs[i], cs[j]))
                sc.do('cg_pr_vt (p2atcst_diff (%s, %s))' % (cs[i], cs[j]))
    # lists
    for _ in range(R.choice([4, 6])):
        n1, n2 = R.choice([(1, 1), (2, 2), (2, 2), (3, 3), (2, 1), (1, 2), (0, 2), (2, 0), (0, 0)])
        l1 = sc.lst('p2atcstlst', [R.choice(cs) for _ in range(n1)])
        l2 = sc.lst('p2atcstlst', [R.choice(cs) for _ in range(n2)])
        a = sc.val(l1, 'p2atcstlst'); b = sc.val(l2, 'p2atcstlst')
        sc.do('(print_p2atcstlst (%s); print_newline ())' % a)
        sc.do('(prerr_p2atcstlst (%s); prerr_newline ())' % b)
        sc.do('(dd_bool (p2atcstlst_inter_test (%s, %s)); dd_nl ())' % (a, b))
        sc.do('cg_pr_vtvt (p2atcstlst_comp (%s))' % a)
        if n1 <= 2 and n2 <= 2:
            sc.do('cg_pr_vtvt (p2atcstlst_diff (%s, %s))' % (a, b))
        sc.do('(print_p2atcstlstlst (%s); print_newline ())' % sc.lst('p2atcstlstlst', [a, b]))
        sc.do('(prerr_p2atcstlstlst (%s); prerr_newline ())' % sc.lst('p2atcstlstlst', [b, a]))
    # records
    for _ in range(R.choice([4, 6])):
        named = R.random() < 0.5
        def rl():
            n = R.choice([0, 1, 2, 3])
            return sc.lst('labp2atcstlst', ['K_LABP2ATCST (%s, %s)' % (lab_of(i, named), R.choice(cs)) for i in sorted(R.sample(range(4), n))])
        a = sc.val(rl(), 'labp2atcstlst'); b = sc.val(rl(), 'labp2atcstlst')
        sc.do('(print_labp2atcstlst (%s); print_newline ())' % a)
        sc.do('(prerr_labp2atcstlst (%s); prerr_newline ())' % b)
        sc.do('(dd_bool (labp2atcstlst_inter_test (%s, %s)); dd_nl ())' % (a, b))
        sc.do('cg_pr_lvtvt (labp2atcstlst_comp (%s))' % a)
        sc.do('cg_pr_lvtvt (labp2atcstlst_diff (%s, %s))' % (a, b))
    x = sc.val('K_LABP2ATCST (%s, %s)' % (lab_of(1, False), R.choice(cs)), 'labp2atcst')
