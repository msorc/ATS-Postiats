# the generator of the cases of the level-2 dynamic test (called by d2_gen.py, see there and PORTING.md "Level 2 dynamic (dynexp2)")
#
# A scenario is a function (a block of 'val' statements) that creates some cells (s2cst, s2var, d2con, d2cst, d2var, d2mac), builds
# random values of the types of pats_dynexp2.spec (the wrappers K_x and the typed lists/options of the compat layers, and the smart
# constructors of pats_dynexp2.sats) and calls the functions of the API, dumping every result completely. The generator writes the neutral
# text that both drivers include. D2SEED (the seed of the random generator) and D2SCALE (the number of scenarios) can be set in the environment.
import os, random, re

SEED = int(os.environ.get('D2SEED', '1'))
SCALE = float(os.environ.get('D2SCALE', '5'))

# --------------------------------------------------------------------------------------------------------------------
def put(path, text):
    """write the file only if it changes (the objects of the unchanged chunks are not rebuilt)"""
    if os.path.exists(path) and open(path).read() == text: return
    open(path, 'w').write(text)

def write_chunks(G, chunks):
    d = G.d
    for f in os.listdir(d):   # remove the files of an older generation (more chunks)
        m = re.match(r'^(?:d2case_|d2case1_|d2cases_)(\d\d)\.(?:dats|hats)$', f)
        if m and int(m.group(1)) >= len(chunks): os.remove(os.path.join(d, f))
    ch2 = []; ch1 = []
    for k, body in enumerate(chunks):
        cases = 'd2cases_%02d.hats' % k
        put(os.path.join(d, cases), body)
        put(os.path.join(d, 'd2case_%02d.dats' % k),
            '(* generated by d2_gen.py: the chunk %d of the cases of the level-2 dynamic test (ATS2) *)\n#define ATS_DYNLOADFLAG 0\n#include "d2case_pre.hats"\n'
            'extern fun tc%d_all (): void = "ext#d2tc_%d"\n#include "%s"\nimplement tc%d_all () = tc%d_body ()\n' % (k, k, k, cases, k, k))
        put(os.path.join(d, 'd2case1_%02d.dats' % k),
            '(* generated by d2_gen.py: the chunk %d of the cases of the level-2 dynamic test (ATS1) *)\n#include "d2case_pre1.hats"\n'
            'extern fun tc%d_all (): void = "d2tc_%d"\n#include "%s"\nimplement tc%d_all () = tc%d_body ()\n' % (k, k, k, cases, k, k))
        ch2.append('extern fun tc%d_all (): void = "ext#d2tc_%d"\n' % (k, k))
        ch1.append('extern fun tc%d_all (): void = "d2tc_%d"\n' % (k, k))
    call = 'fun tc_all (): void = {\n' + ''.join('  val () = tc%d_all ()\n' % k for k in range(len(chunks))) + '}\n'
    put(os.path.join(d, 'd2chunks.hats'), ''.join(ch2) + call)
    put(os.path.join(d, 'd2chunks1.hats'), ''.join(ch1) + call)

