# the smart constructors: the constructor -> the function (the arguments after the location are those of the constructor)
def smart_name(prefix, c):
    return prefix + c[3:].lower()
SMART_DROP = {'D2Eifcasehd': 1}   # the first argument of the constructor (knd) is computed

class Sc:
    """a scenario: the statements, the pools of the handles, the random generator of values"""
    def __init__(self, G, R, name):
        self.G = G; self.R = R; self.name = name
        self.lines = []; self.n = 0
        self.pool = {}      # type -> [names]
        self.cstorder = []
        self.fulls2 = False   # every constructor of s2exp_node (the traversal of pats_staexp2_appenv.hats)
    # ---- statements
    def tmp(self):
        self.n += 1; return 't%d' % self.n
    def val(self, expr, typ=None):
        t = self.tmp()
        self.lines.append('  val %s = %s' % (t, expr))
        if typ: self.pool.setdefault(typ, []).append(t)
        return t
    def do(self, expr):
        self.lines.append('  val () = %s' % expr)
    def dd(self, typ, expr):
        self.lines.append('  val () = (dd_%s (%s); dd_nl ())' % (typ, expr))
    def say(self, text):
        self.lines.append('  val () = (dd_ps "%s"; dd_nl ())' % text)
    def call(self, fname, args, ret):
        e = '%s (%s)' % (fname, ', '.join(args))
        if ret == 'void': self.do(e)
        elif ret == 'fprint': self.do('(%s (dd_out, %s); dd_nl ())' % (fname, ', '.join(args)))
        elif ret == 'print': self.do('(%s (%s); dd_nl ())' % (fname, ', '.join(args)))
        elif ret == 'prerr': self.do('(%s (%s); prerr_newline ())' % (fname, ', '.join(args)))
        else: self.dd(ret, e)
    def text(self):
        body = '\n'.join(self.lines)
        body = re.sub(r'(?<=[ (,])-(?=\d)', '~', body)   # ATS writes the negative literals ~1
        return 'fun %s (): void = {\n  val () = (dd_ps "=== %s"; dd_nl ())\n%s\n}\n' % (self.name, self.name, body)
    # ---- the pools
    def pick(self, typ):
        p = self.pool.get(typ)
        return self.R.choice(p) if p else None
    def handle(self, t, fresh=0.0):
        p = self.pool.get(t)
        if not p or self.R.random() < fresh:
            return self.new(t)
        return self.R.choice(p)
    def new(self, t, **kw):
        return getattr(self, 'new_' + t)(**kw)
    # ---- the cells
    def new_s2rtdat(self):
        return self.val('s2rtdat_make (%s)' % self.leaf('symbol'), 's2rtdat')
    def new_s2rtVar(self):
        return self.val('s2rtVar_make (%s)' % self.leaf('location'), 's2rtVar')
    def new_s2hole(self):
        return self.val('s2hole_make_srt (%s)' % self.R.choice(PRESORTS), 's2hole')
    def new_s2var(self):
        R = self.R
        s = R.choice(PRESORTS)
        if R.random() < 0.5:
            return self.val('s2var_make_srt (%s)' % s, 's2var')
        return self.val('s2var_make_id_srt (%s, %s)' % (self.leaf('symbol'), s), 's2var')
    def new_s2Var(self):
        return self.val('s2Var_make_srt (%s, %s)' % (self.leaf('location'), self.R.choice(PRESORTS)), 's2Var')
    def new_s2VarBound(self):
        return self.val('s2VarBound_make (%s, %s)' % (self.leaf('location'), self.gv('s2exp', 1)), 's2VarBound')
    def new_s2ctxt(self):
        return self.val('s2ctxt_make (%s, %s)' % (self.gv('s2exp', 1), self.handle('s2hole')), 's2ctxt')
    def new_s2cst(self):
        R = self.R
        c = self.val('s2cst_make (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)' % (
            self.leaf('symbol'), self.leaf('location'), self.leaf('filename'), R.choice(PRESORTS),
            'ON_s2expoptopt ()', R.choice(['true', 'false']), R.choice(['true', 'false']),
            'ON_s2expopt ()', 'ON_d2conpairopt ()', 'LN_syms2rtlstlst ()', 'ON_s2expopt ()'), 's2cst')
        self.cstorder.append(c)
        return c
    def new_d2con(self):
        R = self.R
        c = self.handle('s2cst')
        return self.val('d2con_make (%s, %s, %s, %s, %d, %s, %d, %s, ON_s2explstopt ())' % (
            self.leaf('location'), self.leaf('filename'), self.leaf('symbol'), c, R.choice([0, 1]), self.gv('s2qualst', 1),
            R.choice([0, 1, 2]), self.gv('s2explst', 1)), 'd2con')
    def new_d2cst(self):
        R = self.R
        arty = [R.choice([0, 1, 2, 3]) for _ in range(R.choice([0, 1, 1, 2, 3]))]
        return self.val('d2cst_make (%s, %s, %s, %s, %s, %s, %s, %s)' % (
            self.leaf('symbol'), self.leaf('location'), self.leaf('filename'), self.leaf('dcstkind'), self.gv('s2qualst', 1),
            self.lst('intlst', [str(a) for a in arty]), self.gv('s2exp', 1), self.leaf('dcstextdef')), 'd2cst')
    def new_d2var(self):
        R = self.R
        if R.random() < 0.15:
            return self.val('d2var_make_any (%s)' % self.leaf('location'), 'd2var')
        return self.val('d2var_make (%s, %s)' % (self.leaf('location'), self.leaf('symbol')), 'd2var')
    def new_d2mac(self):
        R = self.R
        return self.val('d2mac_make (%s, %s, %d, %s, %s)' % (
            self.leaf('location'), self.leaf('symbol'), R.choice([0, 1]), self.gv('m2acarglst', 1), self.gv('d2exp', 1)), 'd2mac')
    # ---- lists
    def lst(self, alias, elems):
        e = 'LN_%s ()' % alias
        for x in reversed(elems): e = 'LC_%s (%s, %s)' % (alias, x, e)
        return e
    # ---- values
    def leaf(self, t):
        R = self.R
        if t == 'int': return str(R.choice([0, 1, 2, 3, 5, -1, 7, 10, 100]))
        if t == 'bool': return R.choice(['true', 'false'])
        if t == 'char': return "mkchr (%d)" % R.randint(0, 3)
        if t == 'string': return '"s%d"' % R.randint(0, 5)
        if t == 'symbol': return 'mksym (%d)' % R.randint(0, 6)
        if t == 'label': return 'mklab (%d)' % R.randint(0, 3)
        if t == 'location': return 'mkloc (%d)' % R.randint(0, 20)
        if t == 'filename': return 'mkfil (%d)' % R.randint(0, 2)
        if t == 'stamp': return 'mkstamp (%d)' % R.randint(0, 2)
        if t == 'intinf': return 'mkintinf (%d)' % R.randint(0, 20)
        if t == 'funclo': return 'mkfunclo (%d)' % R.randint(0, 3)
        if t == 'effset': return 'mkeffset (%d)' % R.randint(0, 4)
        if t == 'e1xp': return 'mke1xp (%d)' % R.randint(0, 9)
        if t == 'filenv': return 'mkfilenv (%d)' % R.randint(0, 9)
        if t == 'scstextdef': return 'mkscstextdef (%d)' % R.randint(0, 1)
        if t in ('d0ynq', 'l0ab', 'i0de', 'i0nt', 'c0har', 'f0loat', 's0tring', 'cstsp', 'macsynkind', 'dcstextdef', 'dcstkind', 'funkind', 'valkind',
                 'caskind', 'pckind', 'hisexp', 'funlab'):
            return 'mk%s (%d)' % (t, R.randint(0, 9))
        raise Exception('leaf ' + t)
    def sort(self):
        return self.R.choice(PRESORTS)
    def gv(self, t, d):
        """an expression of the type t (d: the depth that is left)"""
        G = self.G; R = self.R
        if t in LEAFT: return self.leaf(t)
        if t in CELLT: return self.handle(t, 0.1)
        if t == 's2rt': return self.sort()
        if t == 's2varord':
            if self.pool.get('s2var') and R.random() < 0.7: return 't_svs_of (%s)' % self.handle('s2var')
            return 't_svs_nil ()'
        if t == 'd2varord':
            if self.pool.get('d2var') and R.random() < 0.7: return 't_dvs_of (%s)' % self.handle('d2var')
            return 't_dvs_nil ()'
        if t in G.lists:
            n = R.choice([0, 1, 1, 2, 2, 3]) if d > 0 else (R.choice([0, 0, 1]) if d > -3 else 0)
            return self.lst(t, [self.gv(G.lists[t], d - 1) for _ in range(n)])
        if t in G.opts:
            if R.random() < 0.35 or d < -3: return 'ON_%s ()' % t
            return 'OS_%s (%s)' % (t, self.gv(G.opts[t], d - 1))
        if t in ('p2at', 'd2exp', 'd2ecl') and self.pool.get(t) and R.random() < 0.4:
            return R.choice(self.pool[t])
        if t in G.recs:
            return self.record(t, d)
        if t in G.types:
            return self.datatype(t, d)
        raise Exception('gv: ' + t)
    def record(self, t, d):
        G = self.G; R = self.R
        fs = G.recs[t]
        if t == 's2exp':
            return 'K_s2exp (%s, %s)' % (R.choice(PRESORTS), self.gv('s2exp_node', d))
        if t == 'labs2exp':
            return 'K_labs2exp (%s, %s, %s)' % (self.leaf('label'), 'ON_stringopt ()', self.gv('s2exp', d - 1))
        if t == 's2exparg':
            return 'K_s2exparg (%s, %s)' % (self.leaf('location'), self.gv('s2exparg_node', d - 1))
        return 'K_%s (%s)' % (t, ', '.join(self.gv(ft, d - 1) for f, ft in fs))
    def datatype(self, t, d):
        G = self.G; R = self.R
        cons = G.types[t]
        names = [c for c, ts in cons]
        if t == 's2exp_node' and not self.fulls2: names = [c for c in names if c in SAFE_S2E]
        if d <= 0 and t in TERM:
            names = [c for c in TERM[t] if c in names] or names
        if t == 'tyreckind': names = TERM['tyreckind']   # (no stamp: the order of evaluation of the arguments is not specified)
        c = R.choice(names)
        ts = dict(cons)[c]
        args = []
        for i, at in enumerate(ts):
            args.append(self.carg(t, c, i, at, d))
        return 'K_%s (%s)' % (c, ', '.join(args))
    def carg(self, t, c, i, at, d):
        R = self.R
        if c == 'S2Eapp' and i == 0: return 's2exp_cst (%s)' % self.handle('s2cst', 0.1)
        if c == 'S2Emetfun' and i == 0: return 'ON_stampopt ()'
        if c == 'S2Etop' and i == 0: return str(R.choice([0, 1]))
        if c in ('S2Etyrec', 'S2Efun') and at == 'int' and i in (1, 3, 2):
            return str(R.choice([0, 0, 1, 2]))
        if c == 'S2Efun' and i == 1: return str(R.choice([0, 1]))
        if c == 'S2ITMfilenv': return self.leaf('filenv')
        return self.gv(at, d - 1)

