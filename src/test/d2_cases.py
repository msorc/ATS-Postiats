        sc.dd('s2exp', 's2exp_hnfize (%s)' % c)
        sc.dd('s2exp', 's2exp_mhnfize (%s)' % a)
        sc.call('s2exp_syneq', [a, b], 'bool'); sc.call('s2exp_syneq', [a, c], 'bool'); sc.call('s2exp_syneq', [b, c], 'bool')
        sc.call('s2exp_syneq', [a, 's2exp_hnfize (%s)' % a], 'bool'); sc.call('s2exp_syneq', ['s2exp_hnfize (%s)' % a, 's2exp_hnfize (%s)' % b], 'bool')
