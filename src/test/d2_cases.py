# ---- the family hnf: the types that the cells of the dynamic syntax hold (d2var, d2cst, p2at), through the REAL functions of
# pats_staexp2_util2/solve/stacst2 (hnfize, syneq, equal/subtyping); the trans2/trans3 environments are the test doubles of s2env1/2.hats.
def hn_tree(R, d, free, bound, ncst, nV):
    """a tree of static expressions: ('int',n) ('cst',i) ('var',v) ('Var',i) ('lam',[b],body) ('app',head,[args]) ('uni'|'exi',[b],[props],body) ('fun',[args],res)"""
    k = R.random()
    if d <= 0 or k < 0.15:
        c = R.random()
        if c < 0.3: return ('int', R.choice([0, 1, 2, 5, 7]))
        if c < 0.55: return ('cst', R.randrange(ncst))
        if c < 0.65 and nV: return ('Var', R.randrange(nV))
        vs = free + bound
        return ('var', R.choice(vs)) if vs else ('int', 3)
    if k < 0.45:   # a beta redex or an application of a constant (with or without definition) or of a bound variable
        n = R.choice([1, 1, 2])
        bs = ['b%d_%d' % (d, i) + chr(97 + R.randrange(26)) for i in range(n)]
        lam = ('lam', bs, hn_tree(R, d - 1, free, bound + bs, ncst, nV))
        head = lam if R.random() < 0.5 else (('cst', R.randrange(ncst)) if R.random() < 0.6 or not (free + bound) else ('var', R.choice(free + bound)))
        return ('app', head, [hn_tree(R, d - 1, free, bound, ncst, nV) for _ in range(R.choice([1, 1, 2]))])
    if k < 0.6:
        bs = ['b%d_%s' % (d, chr(97 + R.randrange(26)))]
        return ('lam', bs, hn_tree(R, d - 1, free, bound + bs, ncst, nV))
    if k < 0.85:
        bs = ['q%d_%s' % (d, chr(97 + R.randrange(26)))]
        ps = [hn_tree(R, d - 1, free, bound + bs, ncst, nV)] if R.random() < 0.5 else []
        return (R.choice(['uni', 'exi']), bs, ps, hn_tree(R, d - 1, free, bound + bs, ncst, nV))
    return ('fun', [hn_tree(R, d - 1, free, bound, ncst, nV) for _ in range(R.choice([0, 1, 2]))], hn_tree(R, d - 1, free, bound, ncst, nV))

def hn_render(sc, t, ren, cs, vs, Vs):
    """the ATS text of a tree; ren maps the names of the binders to the s2var handles"""
    k = t[0]
    r = lambda x: hn_render(sc, x, ren, cs, vs, Vs)
    if k == 'int': return 's2exp_int (%d)' % t[1]
    if k == 'cst': return 's2exp_cst (%s)' % cs[t[1]]
    if k == 'Var': return 's2exp_Var (%s)' % Vs[t[1]]
    if k == 'var': return 's2exp_var (%s)' % (ren[t[1]] if t[1] in ren else vs[int(t[1][1:])])
    if k == 'lam': return 's2exp_lam_srt (s2rt_t0ype, %s, %s)' % (sc.lst('s2varlst', [ren[b] for b in t[1]]), r(t[2]))
    if k == 'app': return 's2exp_app_srt (s2rt_t0ype, %s, %s)' % (r(t[1]), sc.lst('s2explst', [r(x) for x in t[2]]))
    if k in ('uni', 'exi'): return 's2exp_%s (%s, %s, %s)' % (k, sc.lst('s2varlst', [ren[b] for b in t[1]]), sc.lst('s2explst', [r(x) for x in t[2]]), r(t[3]))
    if k == 'fun': return 's2exp_fun_srt (s2rt_t0ype, mkfunclo (0), 0, s2eff_nil, 0, %s, %s)' % (sc.lst('s2explst', [r(x) for x in t[1]]), r(t[2]))
    raise Exception(k)

def hn_binders(t, acc):
    if t[0] in ('lam', 'uni', 'exi'):
        acc.extend(t[1])
    for x in t[1:]:
        if isinstance(x, tuple): hn_binders(x, acc)
        elif isinstance(x, list):
            for y in x:
                if isinstance(y, tuple): hn_binders(y, acc)
    return acc

def hn_mutate(t):
    """the tree with the first integer incremented (or the same tree)"""
    if t[0] == 'int': return ('int', t[1] + 1), True
    out = [t[0]]; done = False
    for x in t[1:]:
        if not done and isinstance(x, tuple):
            x, done = hn_mutate(x)
        elif not done and isinstance(x, list):
            y = []
            for z in x:
                if not done and isinstance(z, tuple): z, done = hn_mutate(z)
                y.append(z)
            x = y
        out.append(x)
    return tuple(out), done

def mkv(sc):
    return sc.val('s2var_make_srt (s2rt_t0ype)', 's2var')

def fam_hnf(sc, k):
    R = sc.R
    ncst = 3
    cs = [sc.new('s2cst') for _ in range(ncst)]
    vs = [mkv(sc) for _ in range(3)]
