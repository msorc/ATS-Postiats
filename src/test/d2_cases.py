    free = ['f%d' % i for i in range(3)]
    ren0 = {}
    # the bindings of the free variables (the table of the test double), the definitions of the constants, the links: acyclic by construction
    sc.do('t_bind_clear ()')
    for i, v in enumerate(vs):
        if R.random() < 0.7:
            body = hn_tree(R, 2, free[:i], [], ncst, 0)
            names = hn_binders(body, [])
