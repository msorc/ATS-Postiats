#!/usr/bin/env python3
# usage: python3 ca_gen.py   (rewrites ca_compat2.hats ca_compat1.hats ca_common2.hats ca_hand_a2.hats ca_hand_a1.hats ca_k2.hats ca_k1.hats ca_cases_NN.hats cacase_NN.dats cacase1_NN.dats ca_chunks*.hats ca_exit.hats)
#
# Test of the C emitter (pats_ccomp_emit{,2,3}.dats) against the ATS1 build of src/ (see PORTING.md, "ccomp group A (emit)").
# Same method as hd_gen.py: ONE generated program of scenarios, written in the common subset of ATS1 and ATS2, is compiled by the ATS2 driver
# (cadump.dats) and by the ATS1 driver (cadump1.dats, linked with the ATS1 objects of $ATS1REF); the C text that the two emit (stdout) and the
# error messages (stderr) must be identical.
#  * ca_compat{2,1}.hats: the layer of hd_gen.py (wrappers K_<CON> of staexp2, dynexp2, dynexp3, histaexp, hidynexp; dumpers), as is;
#  * ca_k{2,1}.hats: the same wrappers for pats_ccomp.spec (the constructors of the trees that the emitter reads), typed lists/options;
#  * ca_cases_<k>.hats: the scenarios (ca_cases.py).
import os, re, sys
sys.dont_write_bytecode = True
d = os.path.dirname(os.path.abspath(__file__))
T = os.path.dirname(d)          # src/test
M = os.path.dirname(T)          # src
sys.path.insert(0, T); sys.path.insert(0, os.path.join(T, 'hd')); sys.path.insert(0, d)
import hd_gen, d2_gen, d2_cases
G = d2_gen

# ---- the ccomp spec (not merged into G: the dumpers of hd_gen are not generated for it)
CC = {'lists': {}, 'opts': {}, 'recs': {}, 'types': {}, 'order': [], 'mut': {}}
def load_cc(path):
    cur = None
    for l in open(path).read().split('\n'):
        l = l.split('#', 1)[0].rstrip()
        if not l: continue
        m = re.match(r'^typedef\s+(\w+)\s*=\s*glist\((\w+)\)\s*$', l)
        if m: CC['lists'][m.group(1)] = m.group(2); continue
        m = re.match(r'^typedef\s+(\w+)\s*=\s*gopt\((\w+)\)\s*$', l)
        if m: CC['opts'][m.group(1)] = m.group(2); continue
        if l.startswith('typedef') or l.startswith('vtypedef'): continue
        m = re.match(r'^record\s+(\w+)\s*\((.*)\)\s*$', l)
        if m:
            fs = []
            for p in G.splitf(m.group(2)):
                mm = re.match(r'^(mut\s+)?(\w+)\s*:\s*(.+)$', p)
                fs.append((mm.group(2), mm.group(3).strip()))
            CC['recs'][m.group(1)] = fs; CC['order'].append(m.group(1)); cur = None
            continue
        m = re.match(r'^type\s+(\w+)\s*$', l)
        if m:
            cur = m.group(1); CC['types'][cur] = []; CC['order'].append(cur); continue
        m = re.match(r'^\s+(\w+)\s*\((.*)\)\s*$', l)
        if m and cur:
            CC['types'][cur].append((m.group(1), [p.strip() for p in G.splitf(m.group(2))])); continue
        raise Exception('spec line: ' + l)
load_cc(os.path.join(M, 'pats_ccomp.spec'))

CC_ABSTRACT = ('tmplab', 'tmpvar', 'funlab', 'funent')      # made by hand (ca_common.hats / ca_hand*.hats)
CC_ONE1 = {'labprimval': 'LABPRIMVAL', 'hifundec2': 'HIFUNDEC2', 'hiimpdec2': 'HIIMPDEC2', 'd2env': 'd2env_make'}   # (ATS1: D2ENV is private to pats_ccomp_d2env.dats)
CC_TUP1 = {'tmpmov': 2}
# ATS1: the [instrlst] of these constructors is the abstract ccomp_instrlst_type (the [where] of pats_ccomp.sats redefines it later): index of the arguments to cast
CC_ATS1_CAST = {'PMDextvar': (1,), 'PMDvaldecs': (2,), 'PMDvaldecs_rec': (2,), 'PMDvardecs': (1,)}
# the list aliases that ATS1 does not have under the name of the spec, and the list/option aliases that G already has
CC_SKIPLST = set(['tmpvarlst_vt', 'tmpmovlst_vt'])

def gen_k_cc(lang):
    o = ['(* generated by ca_gen.py (%s): the wrappers of pats_ccomp.spec *)' % ('ATS1' if lang == 1 else 'ATS2')]
    for a, e in CC['lists'].items():
        if lang == 1:
            o.append('fun LN_%s (): %s = list_nil ()' % (a, a))
            o.append('fun LC_%s (x: %s, xs: %s): %s = list_cons (x, xs)' % (a, e, a, a))
        else:
            o.append('fun LN_%s (): %s = glist_nil ()' % (a, a))
            o.append('fun LC_%s (x: %s, xs: %s): %s = glist_cons<%s> (x, xs)' % (a, e, a, a, e))
    for a, e in CC['opts'].items():
        if lang == 1:
            o.append('fun ON_%s (): %s = None ()' % (a, a))
            o.append('fun OS_%s (x: %s): %s = Some (x)' % (a, e, a))
        else:
            o.append('fun ON_%s (): %s = gopt_none ()' % (a, a))
            o.append('fun OS_%s (x: %s): %s = gopt_some<%s> (x)' % (a, e, a, e))
    o.append('')
    for n in CC['order']:
        if n in CC['recs']:
            if n in CC_ABSTRACT: continue
            fs = CC['recs'][n]
            params = ', '.join('a%d: %s' % (i, t) for i, (f, t) in enumerate(fs))
            args = ', '.join('a%d' % i for i in range(len(fs)))
            if lang == 2:
                o.append('fun K_%s (%s): %s = %s_new (%s)' % (n, params, n, n, args))
            elif n in CC_ONE1:
                o.append('fun K_%s (%s): %s = %s (%s)' % (n, params, n, CC_ONE1[n], args))
            elif n in CC_TUP1:
                o.append('fun K_%s (%s): %s = @(%s)' % (n, params, n, args))
            else:
                o.append("fun K_%s (%s): %s = '{ %s }" % (n, params, n, ', '.join('%s= a%d' % (f, i) for i, (f, t) in enumerate(fs))))
        else:
            for c, ts in CC['types'][n]:
                params = ', '.join('a%d: %s' % (i, t) for i, t in enumerate(ts))
                args = ', '.join('a%d' % i for i in range(len(ts)))
                if lang == 2:
                    o.append('fun K_%s (%s): %s = %s_%s (%s)' % (c, params, n, n, c, args))
                else:
                    cast = CC_ATS1_CAST.get(c, ())
                    args1 = ', '.join(('$UN.cast{ccomp_instrlst_type} (a%d)' if i in cast else 'a%d') % i for i in range(len(ts)))
                    o.append('fun K_%s (%s): %s = %s (%s)' % (c, params, n, c, args1))
    return '\n'.join(o) + '\n'

if __name__ == '__main__':
    put = d2_cases.put
    put(os.path.join(d, 'ca_compat2.hats'), hd_gen.gen_compat(2))
    put(os.path.join(d, 'ca_compat1.hats'), hd_gen.gen_compat(1))
    put(os.path.join(d, 'ca_common2.hats'), hd_gen.common2())
    put(os.path.join(d, 'ca_hand_a2.hats'), hd_gen.hand_a(2))
    # (the ATS1 typedef of the placeholder [instrlst] would shadow the real one of pats_ccomp.sats that is staloaded later: ca_pre1.hats declares it in the first part of a [local])
    put(os.path.join(d, 'ca_hand_a1.hats'), hd_gen.hand_a(1).replace('typedef instrlst = hidynexp_instrlst_type\n', ''))
    put(os.path.join(d, 'ca_k2.hats'), gen_k_cc(2))
    put(os.path.join(d, 'ca_k1.hats'), gen_k_cc(1))
    import ca_cases
    ca_cases.main(G, d2_cases, M, T, d, CC)
