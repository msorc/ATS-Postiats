def f_call(f, ats2=False):
    if f.startswith("pr_"):
        return "%s x" % f
    if f.startswith("dd_"):
        return ("%s (x); nl ()" if ats2 else "%s x; nl ()") % f
    return "%s (out, x); nl ()" % f

