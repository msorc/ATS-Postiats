#!/usr/bin/env python3
# usage: python3 t2_gen.py   (rewrites t2dd.hats t2dd1.hats)
#
# The complete dumpers of the level-2 trees for the whole-file test of the level-2 translation (t2dump.dats, ATS2; t2dump1.dats, ATS1;
# PORTING.md, "Level 2 translation (trans2)"). From ../pats_staexp2.spec and ../pats_dynexp2.spec (through d2_gen.py: every type, every
# constructor, every field) in ATS2 and ATS1. The cells (s2cst, s2var, s2Var, s2rtdat, s2hole, d2con, d2cst, d2var, d2mac) are dumped completely
# (all the fields through the getters, the mutable ones included, stamps included) the first time they are met and as NAME#STAMP afterwards
# (t2dump_seen of t2dump.cats): the structure is cyclic (a constructor refers to its sort, which refers to the constructors; a function to its definition).
# The filenv of a D2Cstaload is dumped with its d2eclist the first time its file is met.
import re, os, sys
sys.dont_write_bytecode = True
d = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, d)
import d2_gen as G

SEEN = {'s2cst': 1, 's2var': 2, 's2Var': 3, 's2rtdat': 4, 's2hole': 5, 'd2con': 6, 'd2cst': 7, 'd2var': 8, 'd2mac': 9}
# getters that ATS1 declares and does not implement (PORTING.md S2-13) or that it does not have
SKIP = set(['s2cst_arylst', 's2cst_iscpy', 's2Var_loc', 's2ctxt_exp', 's2ctxt_hole'])
FTYPE = {'s2Varset': None, 'count': 'count'}

def cells(lang):
    o = []
    for c in ['s2rtdat', 's2cst', 's2var', 's2Var', 's2hole', 'd2con', 'd2cst', 'd2var', 'd2mac']:
        fs = [(f, t) for f, t in G.recs[c] if f not in SKIP]
        stamp = c + '_get_stamp'
        o.append('and dd_%s (x: %s): void =' % (c, c))
        o.append('  if t2dump_seen (%d, $STMP.stamp_get_int (%s x)) > 0 then (dd_ps "%s#"; dd_stamp (%s x))' % (SEEN[c], stamp, c, stamp))
        o.append('  else (')
        o.append('    dd_ps "%s{"' % c)
        for i, (f, t) in enumerate(fs):
            g = '%s_get_%s' % (c, f[len(c) + 1:])
            o.append('    ; dd_ps "%s%s="' % (',' if i else '', f[len(c) + 1:]))
            if t == 's2Varset':
                o.append('    ; fprint_s2Varset (dd_out, %s x)' % g)
            else:
                o.append('    ; dd_%s (%s x)' % (t, g))
        o.append('    ; dd_ps "}")')
        o.append('')
    # the ordered lists of the variables of a pattern, the contexts (not met in the trees)
    if lang == 2:
        for t, e in (('s2varord', 's2var'), ('d2varord', 'd2var')):
            o.append('and dd_%s (x: %s): void = (dd_ps "ord["; dd_%s_aux ($UT.lstord2list<%s> (x), 0); dd_ps "]")' % (t, t, t, e))
            o.append('and dd_%s_aux (xs: glist (%s), i: int): void = case+ glist_view (xs) of' % (t, e))
            o.append('  | ~GLcons (x, xs) => ((if i > 0 then dd_ps ","); dd_%s x; dd_%s_aux (xs, i+1))' % (e, t))
            o.append('  | ~GLnil () => ()')
    else:
        for t, e in (('s2varord', 's2var'), ('d2varord', 'd2var')):
            o.append('and dd_%s (x: %s): void = (dd_ps "ord["; dd_%s_aux ($UT.lstord2list (x), 0); dd_ps "]")' % (t, t, t))
            o.append('and dd_%s_aux (xs: List (%s), i: int): void = case+ xs of' % (t, e))
            o.append('  | list_cons (x, xs) => ((if i > 0 then dd_ps ","); dd_%s x; dd_%s_aux (xs, i+1))' % (e, t))
            o.append('  | list_nil () => ()')
    o.append('and dd_s2ctxt (x: s2ctxt): void = dd_ps "s2ctxt(...)"')
    o.append('')
    # the filenv of a staload (the file is dumped once)
    o.append('and dd_filenv (x: filenv): void =')
    o.append('  (dd_ps "filenv("; dd_filename (filenv_get_name x); dd_ps ";";')
    o.append('   (if t2dump_seen_str ($SYM.symbol_get_name ($FIL.filename_get_fullname (filenv_get_name x))) > 0 then dd_ps "<staloaded>"')
    o.append('    else dd_d2eclist (filenv_get_d2eclist x)); dd_ps ")")')
    o.append('')
    return '\n'.join(o)

def gen(lang):
    txt = G.gen_compat(lang)
    lines = [l for l in txt.split('\n') if not re.match(r'^fun (K_|LN_|LC_|ON_|OS_)', l)]
    # the cells and dd_filenv are part of the recursive group
    return '(* generated by t2_gen.py (%s) *)\n' % ('ATS1' if lang == 1 else 'ATS2') + '\n'.join(lines) + '\n' + cells(lang)

if __name__ == '__main__':
    open(os.path.join(d, 't2dd.hats'), 'w').write(gen(2))
    open(os.path.join(d, 't2dd1.hats'), 'w').write(gen(1))
