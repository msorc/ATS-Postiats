class Sc:
    """a scenario: the statements, the pools of the handles, the random generator of values"""
    def __init__(self, G, R, name, idom=False, nolink=False):
        self.G = G; self.R = R; self.name = name
        self.lines = []; self.n = 0
        self.pool = {}      # type -> [names]
        self.idom = idom    # trees on which the real s2exp_hnfize is the identity (szexp, skexp, util1: no S2Etop, S2Einvar, beta-redex)
        self.nolink = nolink
        self.nozVar = False
        self.varbias = 0.0   # the probability of a variable at a leaf of a tree (substitutions)
        self.cstorder = []  # the s2cst in the order of creation (the superclass relations go downwards)
        self.Vorder = []    # the s2Var in the order of creation
        self.restrict = {}  # type -> the only handles that the random trees may use (acyclic bindings, links and definitions)
        self.nodecnt = 0    # the number of s2exp records that the generator has made (see twin in s2_cases2.py)
        self.mutate_at = None   # the number of the s2exp record that the generator replaces by a leaf (see twin)
        self.forced = None  # the constructor of the root of the next tree (force in s2_cases2.py)
    # ---- statements
    def tmp(self):
        self.n += 1; return 't%d' % self.n
    def val(self, expr, typ=None):
        t = self.tmp()
        self.lines.append('  val %s = %s' % (t, expr))
        if typ: self.pool.setdefault(typ, []).append(t)
        return t
    def do(self, expr):
        self.lines.append('  val () = %s' % expr)
    def dd(self, typ, expr):
        self.lines.append('  val () = (dd_%s (%s); dd_nl ())' % (typ, expr))
    def say(self, text):
        self.lines.append('  val () = (dd_ps "%s"; dd_nl ())' % text)
    def call(self, fname, args, ret):
        """call a function of the API with the given argument expressions and dump the result as [ret]"""
        e = '%s (%s)' % (fname, ', '.join(args))
        if ret == 'void': self.do(e)
        elif ret == 'fprint': self.do('(%s (dd_out, %s); dd_nl ())' % (fname, ', '.join(args)))
        elif ret == 'print': self.do('(%s (%s); dd_nl ())' % (fname, ', '.join(args)))
        elif ret == 'prerr': self.do('(%s (%s); prerr_newline ())' % (fname, ', '.join(args)))
        else: self.dd(ret, e)
    def text(self):
        body = '\n'.join(self.lines)
        body = re.sub(r'(?<=[ (,])-(?=\d)', '~', body)   # ATS writes the negative literals ~1
        return 'fun %s (): void = {\n  val () = (dd_ps "=== %s"; dd_nl ())\n%s\n}\n' % (self.name, self.name, body)
    # ---- the cells
    def pick(self, typ):
        p = self.pool.get(typ)
        return self.R.choice(p) if p else None
    def handle(self, t, fresh=0.0):
        if t in self.restrict:
            return self.R.choice(self.restrict[t]) if self.restrict[t] else self.new(t)
        p = self.pool.get(t)
        if not p or self.R.random() < fresh:
            return self.new(t)
        return self.R.choice(p)
    def new(self, t, **kw):
        return getattr(self, 'new_' + t)(**kw)
    def new_s2rtdat(self):
        return self.val('s2rtdat_make (%s)' % self.leaf('symbol'), 's2rtdat')
    def new_s2rtVar(self):
        return self.val('s2rtVar_make (%s)' % self.leaf('location'), 's2rtVar')
    def new_s2hole(self):
        return self.val('s2hole_make_srt (%s)' % self.gv('s2rt', 1), 's2hole')
    def new_s2var(self, srt=None):
        R = self.R
        s = srt or self.gv('s2rt', 1)
        if R.random() < 0.5:
            return self.val('s2var_make_srt (%s)' % s, 's2var')
        return self.val('s2var_make_id_srt (%s, %s)' % (self.leaf('symbol'), s), 's2var')
    def new_s2Var(self):
        R = self.R
        if R.random() < 0.7:
            v = self.val('s2Var_make_srt (%s, %s)' % (self.leaf('location'), self.gv('s2rt', 1)), 's2Var')
        else:
            v = self.val('s2Var_make_var (%s, %s)' % (self.leaf('location'), self.handle('s2var')), 's2Var')
        self.Vorder.append(v)
        return v
    def new_s2cst(self, fun=False, nofun=False):
        R = self.R
        if fun:
            n = R.choice([1, 1, 2, 3])
            srt = 'K_S2RTfun (%s, %s)' % (self.lst('s2rtlst', [R.choice(PRESORTS) for _ in range(n)]), R.choice(PRESORTS))
            if R.random() < 0.2: srt = 'K_S2RTfun (%s, %s)' % (self.lst('s2rtlst', [R.choice(PRESORTS) for _ in range(2)]), srt)
        elif nofun:
            srt = R.choice(PRESORTS + [self.gv('s2rt', 1)])
            if 'S2RTfun' in srt: srt = 's2rt_t0ype'
        else:
            srt = self.gv('s2rt', 2)
        isabs = R.choice(['ON_s2expoptopt ()', 'ON_s2expoptopt ()', 'OS_s2expoptopt (ON_s2expopt ())', 'OS_s2expoptopt (OS_s2expopt (%s))' % self.gv('s2exp', 1)])
        islst = 'ON_d2conpairopt ()'
        if self.pool.get('d2con') and len(self.pool['d2con']) >= 2 and R.random() < 0.2:
            islst = 'OS_d2conpairopt (K_d2conpair (%s, %s))' % (self.pool['d2con'][0], self.pool['d2con'][1])
        isasp = R.choice(['ON_s2expopt ()', 'ON_s2expopt ()', 'OS_s2expopt (%s)' % self.gv('s2exp', 1)])
        defn = R.choice(['ON_s2expopt ()', 'ON_s2expopt ()', 'OS_s2expopt (%s)' % self.gv('s2exp', 1)])
        c = self.val('s2cst_make (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)' % (
            self.leaf('symbol'), self.leaf('location'), self.leaf('filename'), srt, isabs, R.choice(['true', 'false']),
            R.choice(['true', 'false']), isasp, islst, self.gv('syms2rtlstlst', 1), defn), 's2cst')
        if fun: self.pool.setdefault('s2cst_fun', []).append(c)
        self.cstorder.append(c)
        return c
    def cst_fun(self):
        p = self.pool.get('s2cst_fun')
        if not p or self.R.random() < 0.2: return self.new_s2cst(fun=True)
        return self.R.choice(p)
    def new_d2con(self):
        R = self.R
        withind = R.random() < 0.6
        c = self.cst_fun() if withind else self.handle('s2cst')
        if not withind:   # the type of the result is the constant itself: any sort
            pass
        return self.val('d2con_make (%s, %s, %s, %s, %d, %s, %d, %s, %s)' % (
            self.leaf('location'), self.leaf('filename'), self.leaf('symbol'), c, R.choice([0, 1]), self.gv('s2qualst', 1),
            R.choice([0, 1, 2]), self.gv('s2explst', 1), (self.gv('s2explstopt', 1) if withind else 'ON_s2explstopt ()')), 'd2con')
    def new_s2VarBound(self):
        return self.val('s2VarBound_make (%s, %s)' % (self.leaf('location'), self.gv('s2exp', 1)), 's2VarBound')
    def new_s2ctxt(self):
        return self.val('s2ctxt_make (%s, %s)' % (self.gv('s2exp', 1), self.handle('s2hole')), 's2ctxt')
    # ---- lists
    def lst(self, alias, elems):
        e = 'LN_%s ()' % alias
        for x in reversed(elems): e = 'LC_%s (%s, %s)' % (alias, x, e)
        return e
    # ---- values
    def leaf(self, t):
        R = self.R
        if t == 'int': return str(R.choice([0, 1, 2, 3, 5, -1, 7, 10, 100]))
        if t == 'bool': return R.choice(['true', 'false'])
        if t == 'char': return "mkchr (%d)" % R.randint(0, 3)
        if t == 'string': return '"s%d"' % R.randint(0, 5)
        if t == 'symbol': return 'mksym (%d)' % R.randint(0, 6)
        if t == 'label': return 'mklab (%d)' % R.randint(0, 3)
        if t == 'location': return 'mkloc (%d)' % R.randint(0, 20)
        if t == 'filename': return 'mkfil (%d)' % R.randint(0, 2)
        if t == 'stamp': return 'mkstamp (%d)' % R.randint(0, 2)
        if t == 'intinf': return 'mkintinf (%d)' % R.randint(0, 20)
        if t == 'funclo': return 'mkfunclo (%d)' % R.randint(0, 3)
        if t == 'effset': return 'mkeffset (%d)' % R.randint(0, 4)
        if t == 'e1xp': return 'mke1xp (%d)' % R.randint(0, 9)
        if t == 'filenv': return 'mkfilenv (0)'
        if t == 'scstextdef': return 'mkscstextdef (%d)' % R.randint(0, 1)
        raise Exception('leaf ' + t)
    def sort(self, d):
        R = self.R
        x = R.random()
        if d <= 0 or x < 0.62: return R.choice(BASESORTS if R.random() < 0.5 else PRESORTS)
        if x < 0.66: return 'K_S2RTbas (K_S2RTBASdef (%s))' % self.handle('s2rtdat')
        if x < 0.70: return 'K_S2RTbas (K_S2RTBASpre (%s))' % self.leaf('symbol')
        if x < 0.76: return 'K_S2RTbas (K_S2RTBASimp (%d, %s))' % (R.choice([0, 1, 2, 3, 5, 7, 8, 9, 10, 11, 13, 15, 24, 25, 26, 27, 29, 31]), self.leaf('symbol'))
        if x < 0.86: return 'K_S2RTfun (%s, %s)' % (self.gv('s2rtlst', d - 1), self.sort(d - 1))
        if x < 0.90: return 'K_S2RTtup (%s)' % self.gv('s2rtlst', d - 1)
        if x < 0.97: return 'K_S2RTVar (%s)' % self.handle('s2rtVar', 0.2)
        return 'K_S2RTerr ()'
    def gv(self, t, d):
        """an expression of the type t (d: the depth that is left)"""
        G = self.G; R = self.R
        if t in LEAFT: return self.leaf(t)
        if t in CELLT: return self.handle(t, 0.1)
        if t == 's2rt': return self.sort(d)
        if t in G.lists:
            n = R.choice([0, 1, 1, 2, 2, 3]) if d > 0 else R.choice([0, 0, 1])
            return self.lst(t, [self.gv(G.lists[t], d - 1) for _ in range(n)])
        if t in G.opts:
            if R.random() < 0.35: return 'ON_%s ()' % t
            return 'OS_%s (%s)' % (t, self.gv(G.opts[t], d - 1))
        if t in G.recs:
            return self.record(t, d)
        if t in G.types:
            return self.datatype(t, d)
        raise Exception('gv: ' + t)
    def record(self, t, d):
        G = self.G; R = self.R
        fs = G.recs[t]
        if t == 's2exp':
            return self.s2exp(d)
        if t == 'labs2exp':
            return 'K_labs2exp (%s, %s, %s)' % (self.leaf('label'), self.gv('stringopt', 0), self.gv('s2exp', d - 1))
        if t == 's2exparg':
            return 'K_s2exparg (%s, %s)' % (self.leaf('location'), self.gv('s2exparg_node', d - 1))
        return 'K_%s (%s)' % (t, ', '.join(self.gv(ft, d - 1) for f, ft in fs))
    def s2exp(self, d):
        R = self.R
        if d <= 0 and R.random() < 0.5 and not self.nolink:
            pass
        self.nodecnt += 1
        if self.mutate_at is not None and self.nodecnt == self.mutate_at:
            self.mutate_at = None
            return 'K_s2exp (s2rt_int, K_S2Eint (777))'   # (a node that the original tree does not have)
        srt = self.sort(1) if R.random() < 0.5 else R.choice(PRESORTS)
        return 'K_s2exp (%s, %s)' % (srt, self.gv('s2exp_node', d))
    def s2exp_head(self, d):
        R = self.R
        x = R.random()
        if self.idom or x < 0.7:
            k = R.choice(['cst', 'var', 'cst'] + ([] if self.nolink else ['Var']))
            if k == 'cst': return 's2exp_cst (%s)' % self.handle('s2cst', 0.1)
            if k == 'var': return 's2exp_var (%s)' % self.handle('s2var', 0.1)
            return 's2exp_Var (%s)' % self.handle('s2Var', 0.1)
        return self.gv('s2exp', d)
    def datatype(self, t, d):
        G = self.G; R = self.R
        cons = G.types[t]
        names = [c for c, ts in cons]
        if d <= 0 and t in TERM:
            names = [c for c in TERM[t] if c in names] or names
        if self.nolink and t == 's2exp_node': names = [c for c in names if c not in ('S2EVar', 'S2Ehole')] or names
        if self.idom and t == 's2exp_node': names = [c for c in names if c not in ('S2Etop', 'S2Einvar', 'S2EVar')]
        if self.nozVar and t == 's2zexp': names = [c for c in names if c != 'S2ZEVar']   # (s2zexp_subst_flag loops on a fresh S2ZEVar: the szexp of V is S2ZEVar(V))
        if t == 'tyreckind' and d <= 0: names = TERM['tyreckind']
        c = R.choice(names)
        if t == 's2exp_node' and self.forced:
            c = self.forced; self.forced = None
        if t == 's2exp_node' and 'S2Evar' in names and R.random() < self.varbias: c = 'S2Evar'
        ts = dict(cons)[c]
        args = []
        for i, at in enumerate(ts):
            args.append(self.carg(t, c, i, at, d))
        return 'K_%s (%s)' % (c, ', '.join(args))
    def carg(self, t, c, i, at, d):
        R = self.R
        if c == 'S2Eapp' and i == 0: return self.s2exp_head(d - 1)
        if c == 'S2Elam' and i == 0 and self.pool.get('s2var'): return self.lst('s2varlst', [self.handle('s2var', 0.2) for _ in range(R.choice([0, 1, 2]))])
        if c in ('S2Eexi', 'S2Euni') and i == 0: return self.lst('s2varlst', [self.handle('s2var', 0.3) for _ in range(R.choice([0, 1, 1, 2]))])
        if c in ('S2Eexi', 'S2Euni') and i == 1: return self.gv('s2explst', min(d - 1, 1))
        if c == 'S2Etop' and i == 0: return str(R.choice([0, 1]))
        if c == 'S2Erefarg' and i == 0: return str(R.choice([0, 1]))
        if c in ('S2Etyrec', 'S2Efun') and at == 'int' and i in (1, 3, 2):
            return str(R.choice([0, 0, 1, 2]))
        if c == 'S2Efun' and i == 1: return str(R.choice([0, 1]))
        if c == 'S2Edatconptr' and i == 1: return self.gv('s2exp', d - 1)
        if c in ('S2Edatcontyp', 'S2Edatconptr') and i == 0: return self.handle('d2con', 0.1)
        if c == 'S2ITMfilenv': return self.leaf('filenv')
        if at == 's2exp' or at == 's2explst' or at == 'labs2explst' or at == 's2explstlst':
            return self.gv(at, d - 1)
        return self.gv(at, d - 1)

