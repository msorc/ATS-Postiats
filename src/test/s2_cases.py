def fam_sort(sc, k):
    R = sc.R
    s = sc.val(sc.gv('s2rt', 3), 's2rt')
    t = sc.val(sc.gv('s2rt', 2), 's2rt')
    u = sc.val(sc.gv('s2rt', 2), 's2rt')
    for x in (s, t):
        preds(sc, SORT_PREDS, x)
        sc.call('s2rt_get_pol', [x], 'int')
        sc.dd('s2rt', x)
        sc.call('fprint_s2rt', [x], 'fprint')
        sc.call('print_s2rt', [x], 'print')
        sc.call('prerr_s2rt', [x], 'prerr')
        sc.call('s2rt_linearize', [x], 's2rt')
        sc.call('s2rt_delink', [x], 's2rt')
        sc.call('s2rt_delink_all', [x], 's2rt')
    sc.call('fprint_s2rtlst', [sc.gv('s2rtlst', 2)], 'fprint')
    sc.call('print_s2rtlst', [sc.gv('s2rtlst', 2)], 'print')
    sc.call('prerr_s2rtlst', [sc.gv('s2rtlst', 2)], 'prerr')
