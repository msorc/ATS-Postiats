# the state of the cells at the end of a scenario
def finish(sc):
    sc.say('-- state')
    for t, f in [('s2rtdat', 'chk_s2rtdat'), ('s2cst', 'chk_s2cst'), ('s2var', 'chk_s2var'), ('s2Var', 'chk_s2Var'), ('d2con', 'chk_d2con'), ('s2hole', 'chk_s2hole')]:
        for x in sc.pool.get(t, []):
            sc.do('%s (%s)' % (f, x))
    for x in sc.pool.get('s2rtVar', []):
        sc.dd('s2rtVar', x)

def preds(sc, names, x):
    for n in names: sc.call(n, [x], 'bool')

