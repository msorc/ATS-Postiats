# the generator of the cases of the level-2 test (called by s2_gen.py, see there and PORTING.md "Level 2")
#
# A scenario is a function (a block of 'val' statements) that creates some cells (s2cst, s2var, s2Var, d2con, s2hole,
# s2rtVar, s2rtdat), builds random values of the types of pats_staexp2.spec (the wrappers K_x and the typed lists/options of
# the compat layers) and calls the functions of the API, dumping every result completely. The generator writes the neutral text
# that both drivers include. S2SEED (the seed of the random generator) and S2SCALE (the number of scenarios) can be set in the environment.
import os, random, re

SEED = int(os.environ.get('S2SEED', '1'))
SCALE = float(os.environ.get('S2SCALE', '4'))

# --------------------------------------------------------------------------------------------------------------------
def put(path, text):
    """write the file only if it changes (the objects of the unchanged chunks are not rebuilt)"""
    if os.path.exists(path) and open(path).read() == text: return
    open(path, 'w').write(text)

def write_chunks(G, chunks):
    """chunks: list of bodies (text of 'fun tcK_body (): void = {...}'); writes the chunk files and the lists"""
    d = G.d
    for f in os.listdir(d):   # remove the files of an older generation (more chunks)
        m = re.match(r'^(?:s2case_|s2case1_|s2cases_)(\d+)\.(?:dats|hats)$', f)
        if m and int(m.group(1)) >= len(chunks): os.remove(os.path.join(d, f))
    ch2 = []; ch1 = []
    for k, body in enumerate(chunks):
        cases = 's2cases_%02d.hats' % k
        put(os.path.join(d, cases), body)
        put(os.path.join(d, 's2case_%02d.dats' % k), 
            '(* generated by s2_gen.py: the chunk %d of the cases of the level-2 test (ATS2) *)\n#define ATS_DYNLOADFLAG 0\n#include "s2case_pre.hats"\n'
            'extern fun tc%d_all (): void = "ext#s2tc_%d"\n#include "%s"\nimplement tc%d_all () = tc%d_body ()\n' % (k, k, k, cases, k, k))
        put(os.path.join(d, 's2case1_%02d.dats' % k), 
            '(* generated by s2_gen.py: the chunk %d of the cases of the level-2 test (ATS1) *)\n#include "s2case_pre1.hats"\n'
            'extern fun tc%d_all (): void = "s2tc_%d"\n#include "%s"\nimplement tc%d_all () = tc%d_body ()\n' % (k, k, k, cases, k, k))
        ch2.append('extern fun tc%d_all (): void = "ext#s2tc_%d"\n' % (k, k))
        ch1.append('extern fun tc%d_all (): void = "s2tc_%d"\n' % (k, k))
    call = 'fun tc_all (): void = {\n' + ''.join('  val () = tc%d_all ()\n' % k for k in range(len(chunks))) + '}\n'
    put(os.path.join(d, 's2chunks.hats'), ''.join(ch2) + call)
    put(os.path.join(d, 's2chunks1.hats'), ''.join(ch1) + call)

