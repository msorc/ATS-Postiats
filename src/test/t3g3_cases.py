    KINT = 'g3_kint ()'
    # ---- the static expressions (text)
    def ty_int(sc, k=None):
        R = sc.R
        k = R.randint(0, 9) if k is None else k
        return R.choice(['s2exp_g1int_kind_index_t0ype (g3_kint (), s2exp_int (%d))' % k, 's2exp_int_int_t0ype (%d)' % k, 's2exp_int_t0ype ()'])
    def ty_bool(sc, b):
        return sc.R.choice(['s2exp_bool_bool_t0ype (%s)' % b, 's2exp_bool_index_t0ype (s2exp_bool (%s))' % b, 's2exp_bool_t0ype ()'])
    def ty_char(sc, k):
        return sc.R.choice(['s2exp_char_index_t0ype (s2exp_int_char (mkchr (%d)))' % k, 's2exp_char_t0ype ()', 's2exp_char_int_t0ype (%d)' % (97 + k % 3)])
    def ty_str(sc, n):
        return sc.R.choice(['s2exp_string_index_type (s2exp_intinf (mkintinf (%d)))' % n, 's2exp_string_type ()'])
