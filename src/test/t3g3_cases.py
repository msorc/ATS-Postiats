# the generator of the cases of the test of the level-3 translation, group 3 (called by t3g3_gen.py, see there and PORTING.md "Level 3 translation, group 3")
#
# A scenario is a function (a block of 'val' statements): it creates cells (s2var, s2cst, d2var), builds patterns, types and expressions (the wrappers K_x and
# the typed lists of the compat layers of the level-3 test, plus the smart constructors of pats_dynexp2.sats / pats_dynexp3.sats), sets the environment
# (the pervasive constants, the proof manager) and calls the functions of the four modules through the wrappers [g3_xxx] of t3g3hand.tmpl, which dump the results.
# The pairs (pattern, type) and (expression, type) are mostly well-formed (so that the successful paths run) and sometimes mutated (so that every error runs).
# G3SEED and G3SCALE can be set in the environment.
import os, random, re, sys
sys.dont_write_bytecode = True

SEED = int(os.environ.get('G3SEED', '1'))
SCALE = float(os.environ.get('G3SCALE', '2'))

def chunk_files(d, C, chunks):
    put = C.put
    for f in os.listdir(d):
        m = re.match(r'^(?:t3g3case_|t3g3case1_|t3g3cases_)(\d\d)\.(?:dats|hats)$', f)
        if m and int(m.group(1)) >= len(chunks): os.remove(os.path.join(d, f))
    ch2 = []; ch1 = []
    for k, body in enumerate(chunks):
        cases = 't3g3cases_%02d.hats' % k
        put(os.path.join(d, cases), body)
        put(os.path.join(d, 't3g3case_%02d.dats' % k),
            '(* generated by t3g3_gen.py: the chunk %d of the cases of the test of the level-3 translation, group 3 (ATS2) *)\n#define ATS_DYNLOADFLAG 0\n#include "t3g3case_pre.hats"\n'
            'extern fun t3g3tc%d_all (): void = "ext#t3g3tc_%d"\n#include "%s"\nimplement t3g3tc%d_all () = tc%d_body ()\n' % (k, k, k, cases, k, k))
        put(os.path.join(d, 't3g3case1_%02d.dats' % k),
            '(* generated by t3g3_gen.py: the chunk %d of the cases of the test of the level-3 translation, group 3 (ATS1) *)\n#include "t3g3case_pre1.hats"\n'
            'extern fun t3g3tc%d_all (): void = "t3g3tc_%d"\n#include "%s"\nimplement t3g3tc%d_all () = tc%d_body ()\n' % (k, k, k, cases, k, k))
        ch2.append('extern fun t3g3tc%d_all (): void = "ext#t3g3tc_%d"\n' % (k, k))
        ch1.append('extern fun t3g3tc%d_all (): void = "t3g3tc_%d"\n' % (k, k))
    call = 'fun t3g3tc_all (): void = {\n' + ''.join('  val () = t3g3tc%d_all ()\n' % k for k in range(len(chunks))) + '}\n'
    put(os.path.join(d, 't3g3chunks.hats'), ''.join(ch2) + call)
    put(os.path.join(d, 't3g3chunks1.hats'), ''.join(ch1) + call)

