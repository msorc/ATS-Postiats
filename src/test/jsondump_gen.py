#!/usr/bin/env python3
# usage: python3 jsondump_gen.py   (rewrites jzdump1.hats and jzdump.hats)
#
# Generates, from ../pats_syntax.spec, a JSON-izer of the complete level-0 syntax tree in ATS1 (jzdump1.hats, for
# tooldump1.dats) and in ATS2 (jzdump.hats, for tooldump.dats), written with the library of pats_jsonize.{sats,dats}
# (jsonval_labvalN for the records, jsonval_conargN/conarglst for the constructors, jsonize_list_fun/jsonize_option_fun
# for the lists and options, jsonize_location/symbol/label/filename/funkind/valkind for the leaves).
# pats_jsonize_synent2.dats (the JSON-izer of the level-2 trees) is not ported yet; this is the level-0 equivalent used
# by the differential test (the output of ATS1 and ATS2 must be identical).
import re, os

d = os.path.dirname(os.path.abspath(__file__))
spec = open(os.path.join(d, '..', 'pats_syntax.spec')).read().split('\n')

lists = {}; opts = {}; recs = {}; types = {}; order = []

def splitf(a):
    parts = []; dep = 0; b = ''
    for ch in a:
        if ch in '(': dep += 1
        if ch in ')': dep -= 1
        if ch == ',' and dep == 0: parts.append(b.strip()); b = ''; continue
        b += ch
    if b.strip(): parts.append(b.strip())
    return parts

cur = None
for l in spec:
    l = l.split('#', 1)[0].rstrip()
    if not l: continue
    m = re.match(r'^typedef\s+(\w+)\s*=\s*glist\((\w+)\)\s*$', l)
    if m: lists[m.group(1)] = m.group(2); continue
    m = re.match(r'^typedef\s+(\w+)\s*=\s*gopt\((\w+)\)\s*$', l)
    if m: opts[m.group(1)] = m.group(2); continue
    if l.startswith('typedef') or l.startswith('vtypedef'): continue
    m = re.match(r'^record\s+(\w+)\s*\((.*)\)\s*$', l)
    if m:
        recs[m.group(1)] = [tuple(x.strip() for x in p.split(':')) for p in splitf(m.group(2))]
        order.append(m.group(1)); cur = None; continue
    m = re.match(r'^type\s+(\w+)\s*$', l)
    if m: cur = m.group(1); types[cur] = []; order.append(cur); continue
    m = re.match(r'^\s+(\w+)\s*\((.*)\)\s*$', l)
    if m and cur:
        types[cur].append((m.group(1), [p.strip() for p in splitf(m.group(2))])); continue
    raise Exception('spec line: ' + l)

lists['symbolist'] = 'symbol'
opts['symbolopt'] = 'symbol'

SPECIAL1 = {'labs0exp': 'SL0ABELED', 'labd0exp': 'DL0ABELED', 'datsdef': 'DATSDEF'}

def labval(n, args):
    # args: [(label, jsonexp)]
    assert 1 <= len(args) <= 8
    return 'jsonval_labval%d (%s)' % (len(args), ', '.join('"%s", %s' % (l, e) for l, e in args))

def conarg(c, es):
    if len(es) <= 4:
        return 'jsonval_conarg%d (%s)' % (len(es), ', '.join(['"%s"' % c] + es))
    lst = 'jz_nil ()'
    for e in reversed(es): lst = 'jz_cons (%s, %s)' % (e, lst)
    return 'jsonval_conarglst ("%s", %s)' % (c, lst)

def jz(t, v):
    return 'jz_%s (%s)' % (t, v)

def gen(lang):
    o = []
    a2 = lang == 2
    fn = 'fn' if a2 else 'fun'
    o.append('(* generated by jsondump_gen.py: JSON-izer of the level-0 tree (ATS%d) *)' % lang)
    if a2:
        o.append('fn jz_nil (): jsonvalist = glist_nil ()')
        o.append('fn jz_cons (x: jsonval, xs: jsonvalist): jsonvalist = glist_cons (x, xs)')
    else:
        o.append('fun jz_nil (): jsonvalist = list_nil ()')
        o.append('fun jz_cons (x: jsonval, xs: jsonvalist): jsonvalist = list_cons (x, xs)')
    leafs = [('location', 'jsonize_location'), ('symbol', 'jsonize_symbol'), ('label', 'jsonize_label'),
             ('filename', 'jsonize_filename'), ('int', 'jsonval_int'), ('bool', 'jsonval_bool'), ('string', 'jsonval_string'),
             ('funkind', 'jsonize_funkind'), ('valkind', 'jsonize_valkind')]
    for t, f in leafs:
        o.append('%s jz_%s (x: %s): jsonval = %s (x)' % (fn, t, t, f))
    for t in ('token', 'i0nt', 'c0har', 'f0loat', 's0tring'):
        o.append('%s jz_%s (x: %s): jsonval = jz_tok (x)' % (fn, t, t))
    o.append('%s jz_cstsp (x: cstsp): jsonval = jz_via (fprint_cstsp, x)' % fn if False else '')
    o.append('%s jz_cstsp (x: cstsp): jsonval = let val f = jz_tmp_begin () val () = fprint_cstsp (f, x) in jsonval_string (jz_tmp_end (f)) end' % fn)
    o.append('%s jz_e0xpactkind (x: e0xpactkind): jsonval = let val f = jz_tmp_begin () val () = fprint_e0xpactkind (f, x) in jsonval_string (jz_tmp_end (f)) end' % fn)
    o.append('%s jz_macsynkind (x: macsynkind): jsonval = let val f = jz_tmp_begin () val () = fprint_macsynkind (f, x) in jsonval_string (jz_tmp_end (f)) end' % fn)
    o.append('%s jz_srpifkind (x: srpifkind): jsonval = (case+ x of SRPIFKINDif () => jsonval_string "if" | SRPIFKINDifdef () => jsonval_string "ifdef" | SRPIFKINDifndef () => jsonval_string "ifndef")' % fn)
    o.append('%s jz_assoc (x: assoc): jsonval = (case+ x of ASSOCnon () => jsonval_string "ASSOCnon" | ASSOClft () => jsonval_string "ASSOClft" | ASSOCrgt () => jsonval_string "ASSOCrgt")' % fn)
    o.append('%s jz_S0Ed2ctype (x: S0Ed2ctype): jsonval = %s' % (fn, 'jsonize_ignored<S0Ed2ctype> (x)' if a2 else 'jsonize_ignored (x)'))
    first = True
    def kw():
        nonlocal first
        k = 'fun' if first else 'and'
        first = False
        return k
    for n in order:
        if n in recs:
            fs = recs[n]
            if n in SPECIAL1 and not a2:
                con = SPECIAL1[n]
                vs = ['f%d' % i for i in range(len(fs))]
                e = labval(n, [(f, jz(t, v)) for (f, t), v in zip(fs, vs)])
                o.append('%s jz_%s (x: %s): jsonval = case+ x of %s (%s) => (%s)' % (kw(), n, n, con, ', '.join(vs), e))
            else:
                acc = (lambda f: 'x.%s()' % f) if a2 else (lambda f: 'x.%s' % f)
                e = labval(n, [(f, jz(t, acc(f))) for f, t in fs])
                o.append('%s jz_%s (x: %s): jsonval = %s' % (kw(), n, n, e))
        else:
            arms = []
            for c, ts in types[n]:
                cc = c
                if not a2 and c == 'D0Cextype2': cc = 'D0Cextype'
                vs = ['a%d' % i for i in range(len(ts))]
                if a2:
                    pat = '~%s (%s)' % (c, ', '.join(vs)) if vs else '~%s ()' % c
                else:
                    pat = '%s (%s)' % (cc, ', '.join(vs)) if vs else '%s ()' % cc
                es = [jz(t, v) for v, t in zip(vs, ts)]
                arms.append('  | %s => (%s)' % (pat, conarg(c, es) if es else 'jsonval_conarg0 ("%s")' % c))
            if a2:
                o.append('%s jz_%s (x: %s): jsonval = case+ %s_view (x) of\n%s' % (kw(), n, n, n, '\n'.join(arms)))
            else:
                o.append('%s jz_%s (x: %s): jsonval = case+ x of\n%s' % (kw(), n, n, '\n'.join(arms)))
    for a, e in lists.items():
        if a2:
            o.append('%s jz_%s (xs: %s): jsonval = jsonize_list_fun<%s> (xs, jz_%s)' % (kw(), a, a, e, e))
        else:
            o.append('%s jz_%s (xs: %s): jsonval = jsonize_list_fun<%s> (xs, jz_%s)' % (kw(), a, a, e, e))
    for a, e in opts.items():
        o.append('%s jz_%s (x: %s): jsonval = jsonize_option_fun<%s> (x, jz_%s)' % (kw(), a, a, e, e))
    return '\n'.join(x for x in o if x) + '\n'

open(os.path.join(d, 'jzdump1.hats'), 'w').write(gen(1))
open(os.path.join(d, 'jzdump.hats'), 'w').write(gen(2))
