#!/usr/bin/env python3
# usage: python3 d2_gen.py   (rewrites d2compat_gen.hats d2compat1_gen.hats d2cases_*.hats d2case_*.dats d2case1_*.dats d2chunks*.hats)
#
# Test of the level-2 dynamic syntax (pats_dynexp2{,_dcst,_dmac,_dvar,_mapgen,_print,_util}) against the ATS1 build of src/
# (see PORTING.md, "Level 2 dynamic (dynexp2)"). Same method as s2_gen.py: ONE generated program of test cases, written in the common
# subset of ATS1 and ATS2, is compiled by the ATS2 driver (d2dump.dats, with ../pats_dynexp2*.dats) and by the ATS1 driver
# (d2dump1.dats, linked with the ATS1 objects of $ATS1REF); the stdout and the stderr of the two must be identical.
#
#  * d2compat_gen.hats / d2compat1_gen.hats: from ../pats_staexp2.spec and ../pats_dynexp2.spec, in ATS2 and ATS1: a wrapper K_<CON> for
#    every constructor and record, the typed list/option helpers (LN_/LC_/ON_/OS_), and a COMPLETE dumper dd_<T> of every type (every
#    constructor, every field; the cells d2cst/d2var/d2mac and the static cells are dumped through their getters).
#  * d2cases_<k>.hats: the scenarios (d2_cases.py), random trees of every type and calls of every function of the 7 modules.
import re, os, sys
sys.dont_write_bytecode = True

d = os.path.dirname(os.path.abspath(__file__))

def splitf(a):
    parts = []; dep = 0; b = ''
    for ch in a:
        if ch == '(': dep += 1
        if ch == ')': dep -= 1
        if ch == ',' and dep == 0: parts.append(b.strip()); b = ''; continue
        b += ch
    if b.strip(): parts.append(b.strip())
    return parts

lists = {'e1xplst': 'e1xp', 'i0delst': 'i0de'}
opts = {'stampopt': 'stamp', 'symbolopt': 'symbol'}
recs = {}; types = {}; order = []; mut = {}; d2order = []
for spname in ['pats_staexp2.spec', 'pats_dynexp2.spec']:
    cur = None
    for l in open(os.path.join(d, '..', spname)).read().split('\n'):
        l = l.split('#', 1)[0].rstrip()
        if not l: continue
        if re.match(r'^viewfn\s', l): continue
        m = re.match(r'^typedef\s+(\w+)\s*=\s*glist\((\w+)\)\s*$', l)
        if m: lists[m.group(1)] = m.group(2); continue
        m = re.match(r'^typedef\s+(\w+)\s*=\s*gopt\((\w+)\)\s*$', l)
        if m: opts[m.group(1)] = m.group(2); continue
        if l.startswith('typedef') or l.startswith('vtypedef'): continue
        m = re.match(r'^record\s+(\w+)\s*\((.*)\)\s*$', l)
        if m:
            fs = []
            for p in splitf(m.group(2)):
                mm = re.match(r'^(mut\s+)?(\w+)\s*:\s*(.+)$', p)
                fs.append((mm.group(2), mm.group(3).strip()))
                if mm.group(1): mut.setdefault(m.group(1), []).append(mm.group(2))
            recs[m.group(1)] = fs; order.append(m.group(1)); cur = None
            if spname == 'pats_dynexp2.spec': d2order.append(m.group(1))
            continue
        m = re.match(r'^type\s+(\w+)\s*$', l)
        if m:
            cur = m.group(1); types[cur] = []; order.append(cur)
            if spname == 'pats_dynexp2.spec': d2order.append(cur)
            continue
        m = re.match(r'^\s+(\w+)\s*\((.*)\)\s*$', l)
        if m and cur:
            types[cur].append((m.group(1), [p.strip() for p in splitf(m.group(2))])); continue
        raise Exception('spec line: ' + l)

# the cells (ATS1: ref (struct)), dumped by hand through their getters
S2CELLS = ['s2rtdat', 's2rtVar', 's2cst', 's2var', 's2Var', 's2VarBound', 's2hole', 's2ctxt', 'd2con']
D2CELLS = ['d2cst', 'd2var', 'd2mac']
CELLS = S2CELLS + D2CELLS
# records that are one-constructor datatypes / tuples / flat records / '{..} records in ATS1
ONE1 = {'labs2exp': 'SLABELED', 'labs2kexp': 'SKLABELED', 'labs2zexp': 'SZLABELED', 'labd2exp': 'DL0ABELED'}
TUP1 = {'locs2exp': 2, 'syms2rt': 2, 'd2conpair': 2}
ATS1TYPE = {
  'd2conpair': '@(d2con, d2con)',
  'locs2exp': '(location, s2exp)',
  'syms2rt': '(symbol, s2rt)',
}
# leaf types: the dumper is written by hand (d2common1.hats / d2compat_hand*.hats)
LEAF = set(('int bool char string symbol label location filename stamp intinf funclo effset Stropt e1xp filenv scstextdef count '
            'd0ynq l0ab i0de i0nt c0har f0loat s0tring cstsp macsynkind dcstextdef dcstkind funkind valkind caskind pckind hisexp funlab '
            's2varord d2varord').split())
# the types that have no K_ wrapper (hand written maker or a leaf)
def known(t):
    return t in recs or t in types or t in lists or t in opts or t in LEAF or t in CELLS
for r, fs in recs.items():
    if r in CELLS: continue
    for f, t in fs: assert known(t), (r, f, t)
for n, cs in types.items():
    for c, ts in cs:
        for t in ts: assert known(t), (n, c, t)

def ats1ty(t):
    return ATS1TYPE.get(t, t)

# ------------------------------------------------------------------------------------ the generated compat layers
def gen_compat(lang):
    o = []
    o.append('(* generated by d2_gen.py (%s): wrappers of the constructors, typed lists/options, complete dumpers *)' % ('ATS1' if lang == 1 else 'ATS2'))
    for a, e in lists.items():
        if lang == 1:
            o.append('fun LN_%s (): %s = list_nil ()' % (a, a))
            o.append('fun LC_%s (x: %s, xs: %s): %s = list_cons (x, xs)' % (a, ats1ty(e), a, a))
        else:
            o.append('fun LN_%s (): %s = glist_nil ()' % (a, a))
            o.append('fun LC_%s (x: %s, xs: %s): %s = glist_cons<%s> (x, xs)' % (a, e, a, a, e))
    for a, e in opts.items():
        if lang == 1:
            o.append('fun ON_%s (): %s = None ()' % (a, a))
            o.append('fun OS_%s (x: %s): %s = Some (x)' % (a, ats1ty(e), a))
        else:
            o.append('fun ON_%s (): %s = gopt_none ()' % (a, a))
            o.append('fun OS_%s (x: %s): %s = gopt_some<%s> (x)' % (a, e, a, e))
    o.append('')
    for n in order:
        if n in recs:
            if n in CELLS: continue
            fs = recs[n]
            params = ', '.join('a%d: %s' % (i, ats1ty(t) if lang == 1 else t) for i, (f, t) in enumerate(fs))
            args = ', '.join('a%d' % i for i in range(len(fs)))
            if lang == 2:
                o.append('fun K_%s (%s): %s = %s_new (%s)' % (n, params, n, n, args))
            elif n == 'd2varlstref':
                o.append('fun K_%s (%s): %s = ref (a0)' % (n, params, n))
            elif n in ONE1:
                o.append('fun K_%s (%s): %s = %s (%s)' % (n, params, n, ONE1[n], args))
            elif n in TUP1:
                o.append('fun K_%s (%s): %s = @(%s)' % (n, params, ats1ty(n), args))
            elif n == 's2qua':
                o.append("fun K_%s (%s): %s = @{ %s }" % (n, params, n, ', '.join('%s= a%d' % (f, i) for i, (f, t) in enumerate(fs))))
            else:
                o.append("fun K_%s (%s): %s = '{ %s }" % (n, params, n, ', '.join('%s= a%d' % (f, i) for i, (f, t) in enumerate(fs))))
        else:
            for c, ts in types[n]:
                params = ', '.join('a%d: %s' % (i, ats1ty(t) if lang == 1 else t) for i, t in enumerate(ts))
                args = ', '.join('a%d' % i for i in range(len(ts)))
                if lang == 2:
                    o.append('fun K_%s (%s): %s = %s_%s (%s)' % (c, params, n, n, c, args))
                else:
                    o.append('fun K_%s (%s): %s = %s (%s)' % (c, params, n, c, args))
    o.append('')
    first = [True]
    def kw():
        k = 'fun' if first[0] else 'and'
        first[0] = False
        return k
    def ddname(t):
        return 'dd_' + t
    for n in order:
        if n in CELLS: continue
        if n in recs:
            fs = recs[n]
            body = ['dd_ps "%s{"' % n]
            for i, (f, t) in enumerate(fs):
                body.append('dd_ps "%s%s="' % (',' if i else '', f))
                if n == 'd2varlstref':
                    body.append('%s (%s)' % (ddname(t), 'd2varlstref_val (x)' if lang == 2 else '!x'))
                elif lang == 2:
                    body.append('%s (%s (x))' % (ddname(t), f))
                elif n in ONE1:
                    body.append('%s f%d' % (ddname(t), i))
                elif n in TUP1:
                    body.append('%s (x.%d)' % (ddname(t), i))
                else:
                    body.append('%s (x.%s)' % (ddname(t), f))
            body.append('dd_ps "}"')
            if lang == 1 and n in ONE1:
                o.append('%s dd_%s (x: %s): void = case+ x of %s (%s) => (%s)\n' % (kw(), n, n, ONE1[n], ', '.join('f%d' % i for i in range(len(fs))), '; '.join(body)))
            else:
                o.append('%s dd_%s (x: %s): void = (%s)\n' % (kw(), n, ats1ty(n) if lang == 1 else n, '; '.join(body)))
        else:
            arms = []
            for c, ts in types[n]:
                vs = ['a%d' % i for i in range(len(ts))]
                pat = ('~%s (%s)' if lang == 2 else '%s (%s)') % (c, ', '.join(vs))
                parts = ['dd_ps "%s("' % c]
                for i, (v, t) in enumerate(zip(vs, ts)):
                    if i: parts.append('dd_ps ","')
                    parts.append('%s (%s)' % (ddname(t), v))
                parts.append('dd_ps ")"')
                arms.append('  | %s => (%s)' % (pat, '; '.join(parts)))
            if lang == 1:
                o.append('%s dd_%s (x: %s): void = case+ x of\n%s\n' % (kw(), n, n, '\n'.join(arms)))
            else:
                o.append('%s dd_%s (x: %s): void = case+ %s (x) of\n%s\n' % (kw(), n, n, 's2rt_viewof' if n == 's2rt' else n + '_view', '\n'.join(arms)))
    o.append('%s dd_s2rtVar (x: s2rtVar): void = (dd_ps "s2rtVar{"; dd_s2rt (s2rtVar_get_s2rt x); dd_ps "}")\n' % kw())
    o.append('%s dd_s2VarBound (x: s2VarBound): void =\n  (dd_ps "bound("; dd_location (s2VarBound_get_loc x); dd_ps ";"; dd_s2exp (s2VarBound_get_val x); dd_ps ")")\n' % kw())
    for a, e in lists.items():
        o.append('%s dd_%s (xs: %s): void = (dd_ps "["; dd_%s_aux (xs, 0); dd_ps "]")\n' % (kw(), a, a, a))
        if lang == 1:
            o.append('and dd_%s_aux (xs: %s, i: int): void = case+ xs of\n  | list_cons (x, xs1) => ((if i > 0 then dd_ps ","); dd_%s x; dd_%s_aux (xs1, i+1))\n  | list_nil () => ()\n' % (a, a, e, a))
        else:
            o.append('and dd_%s_aux (xs: %s, i: int): void = case+ glist_view (xs) of\n  | ~GLcons (x, xs1) => ((if i > 0 then dd_ps ","); dd_%s (x); dd_%s_aux (xs1, i+1))\n  | ~GLnil () => ()\n' % (a, a, e, a))
    for a, e in opts.items():
        if lang == 1:
            o.append('and dd_%s (x: %s): void = case+ x of\n  | Some y => (dd_ps "some("; dd_%s y; dd_ps ")")\n  | None () => dd_ps "-"\n' % (a, a, e))
        else:
            o.append('and dd_%s (x: %s): void = case+ gopt_view (x) of\n  | ~GOsome (y) => (dd_ps "some("; dd_%s (y); dd_ps ")")\n  | ~GOnone () => dd_ps "-"\n' % (a, a, e))
    return '\n'.join(o)

if __name__ == '__main__':
    import d2_cases
    d2_cases.put(os.path.join(d, 'd2compat_gen.hats'), gen_compat(2))
    d2_cases.put(os.path.join(d, 'd2compat1_gen.hats'), gen_compat(1))
    d2_cases.main(sys.modules[__name__])
