#!/usr/bin/env python3
# usage: python3 m2_gen.py   (rewrites d2compat_gen.hats d2compat1_gen.hats m2cases_*.hats m2case_*.dats m2case1_*.dats m2chunks*.hats)
#
# Test of the macro evaluator (pats_dmacro2, _eval0, _eval1, _print, and the error list of pats_trans3_error) against the ATS1 build of src/
# (see PORTING.md, "Macros (dmacro2)"). Same method as d2_gen.py: ONE generated program of scenarios, written in the common subset of ATS1 and
# ATS2, is compiled by the ATS2 driver (m2dump.dats) and by the ATS1 driver (m2dump1.dats, linked with the ATS1 objects of $ATS1REF); the
# stdout and the stderr of the two must be identical. The compat layers of the trees are those of d2_gen.py (d2compat_gen.hats...), the macro
# values are in m2compat_hand.hats / m2compat1_hand.hats; the scenarios are in m2_cases.py.
import os, re, sys
sys.dont_write_bytecode = True
d = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, d)
import d2_gen
import d2_cases
import m2_cases

def write_chunks(G, chunks):
    for f in os.listdir(d):   # remove the files of an older generation (more chunks)
        m = re.match(r'^(?:m2case_|m2case1_|m2cases_)(\d\d)\.(?:dats|hats)$', f)
        if m and int(m.group(1)) >= len(chunks): os.remove(os.path.join(d, f))
    ch2 = []; ch1 = []
    for k, body in enumerate(chunks):
        cases = 'm2cases_%02d.hats' % k
        d2_cases.put(os.path.join(d, cases), body)
        d2_cases.put(os.path.join(d, 'm2case_%02d.dats' % k),
            '(* generated by m2_gen.py: the chunk %d of the cases of the macro test (ATS2) *)\n#define ATS_DYNLOADFLAG 0\n#include "m2case_pre.hats"\n'
            'extern fun mtc%d_all (): void = "ext#m2tc_%d"\n#include "%s"\nimplement mtc%d_all () = tc%d_body ()\n' % (k, k, k, cases, k, k))
        d2_cases.put(os.path.join(d, 'm2case1_%02d.dats' % k),
            '(* generated by m2_gen.py: the chunk %d of the cases of the macro test (ATS1) *)\n#include "m2case_pre1.hats"\n'
            'extern fun mtc%d_all (): void = "m2tc_%d"\n#include "%s"\nimplement mtc%d_all () = tc%d_body ()\n' % (k, k, k, cases, k, k))
        ch2.append('extern fun mtc%d_all (): void = "ext#m2tc_%d"\n' % (k, k))
        ch1.append('extern fun mtc%d_all (): void = "m2tc_%d"\n' % (k, k))
    # the last chunk holds the scenarios that end the process: run only when M2EXIT is set (m2exit.sh), the others only when it is not
    last = len(chunks) - 1
    call = 'fun mtc_all (): void = {\n' + ''.join('  val () = mtc%d_all ()\n' % k for k in range(last)) + '}\n'
    call += 'fun mtc_main (): void = if m2_exit_arg () > 0 then mtc%d_all () else mtc_all ()\n' % last
    d2_cases.put(os.path.join(d, 'm2chunks.hats'), ''.join(ch2) + call)
    d2_cases.put(os.path.join(d, 'm2chunks1.hats'), ''.join(ch1) + call)

if __name__ == '__main__':
    d2_cases.put(os.path.join(d, 'd2compat_gen.hats'), d2_gen.gen_compat(2))
    d2_cases.put(os.path.join(d, 'd2compat1_gen.hats'), d2_gen.gen_compat(1))
    m2_cases.main(d2_gen, write_chunks)
