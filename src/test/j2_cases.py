# the generator of the cases of the test of the level-2 jsonize (called by j2_gen.py, see there and PORTING.md "Level-2 jsonize")
#
# A scenario is a function (a block of 'val' statements): it creates cells (s2var, s2Var, s2cst, d2var, d2con, d2cst), builds random trees of the level-2
# syntax (the wrappers K_x and the typed lists/options of the compat layers of the level-3 test) and calls the functions of pats_jsonize_synent2.sats,
# printing the JSON text of every result (fprint_jsonval). J2SEED and J2SCALE can be set in the environment.
import os, random, re, sys
sys.dont_write_bytecode = True

SEED = int(os.environ.get('J2SEED', '1'))
SCALE = float(os.environ.get('J2SCALE', '2'))

def chunk_files(d, C, chunks):
    put = C.put
    for f in os.listdir(d):
        m = re.match(r'^(?:j2case_|j2case1_|j2cases_)(\d\d)\.(?:dats|hats)$', f)
        if m and int(m.group(1)) >= len(chunks): os.remove(os.path.join(d, f))
    ch2 = []; ch1 = []
    for k, body in enumerate(chunks):
        cases = 'j2cases_%02d.hats' % k
        put(os.path.join(d, cases), body)
        put(os.path.join(d, 'j2case_%02d.dats' % k),
            '(* generated by j2_gen.py: the chunk %d of the cases of the test of the level-2 jsonize (ATS2) *)\n#define ATS_DYNLOADFLAG 0\n#include "j2case_pre.hats"\n'
            'extern fun j2tc%d_all (): void = "ext#j2tc_%d"\n#include "%s"\nimplement j2tc%d_all () = tc%d_body ()\n' % (k, k, k, cases, k, k))
        put(os.path.join(d, 'j2case1_%02d.dats' % k),
            '(* generated by j2_gen.py: the chunk %d of the cases of the test of the level-2 jsonize (ATS1) *)\n#include "j2case_pre1.hats"\n'
            'extern fun j2tc%d_all (): void = "j2tc_%d"\n#include "%s"\nimplement j2tc%d_all () = tc%d_body ()\n' % (k, k, k, cases, k, k))
        ch2.append('extern fun j2tc%d_all (): void = "ext#j2tc_%d"\n' % (k, k))
        ch1.append('extern fun j2tc%d_all (): void = "j2tc_%d"\n' % (k, k))
    call = 'fun j2tc_all (): void = {\n' + ''.join('  val () = j2tc%d_all ()\n' % k for k in range(len(chunks))) + '}\n'
    put(os.path.join(d, 'j2chunks.hats'), ''.join(ch2) + call)
    put(os.path.join(d, 'j2chunks1.hats'), ''.join(ch1) + call)


# ---------------------------------------------------------------------------------------------------------------------
def families(G, C, Sc3, d):
    import t3_cases
    F3 = t3_cases.families(G, C, Sc3, [], d)
    SETUP = [f for f in F3 if f[0] == 'setup'][0]
    F = []
    def S(sc, t, dp=1): return sc.gv(t, dp)
    def js(sc, fname, args):
        sc.call(fname, args, 'jsonval')
    def flush(sc): sc.do('prerr_the_staerrlst ()')


    # ----------------------------------------------------------------------------------------------------------
    # the statics: sorts, cells, expressions
    def fam_static(sc, k):
        R = sc.R
        sc.pools()
        sc.say('-- sorts')
        for _ in range(3):
            js(sc, 'jsonize_s2rt', [S(sc, 's2rt', 2)])
            js(sc, 'jsonize_s2rtlst', [S(sc, 's2rtlst', 2)])
        # the sorts of the cells: functions, tuples, datasorts, linked sort variables
        sd = sc.new('s2rtdat'); sc.do('s2rtdat_set_sconlst (%s, %s)' % (sd, sc.lst('s2cstlst', [sc.handle('s2cst', 0.5) for _ in range(R.choice([0, 1, 2]))])))
        sv = sc.new('s2rtVar')
        sc.do('s2rtVar_set_s2rt (%s, s2rt_prop)' % sv)
        sv2 = sc.new('s2rtVar'); sc.do('s2rtVar_set_s2rt (%s, K_S2RTtup (%s))' % (sv2, sc.lst('s2rtlst', ['s2rt_int', 'K_S2RTVar (%s)' % sv])))
        for srt in ('K_S2RTbas (K_S2RTBASdef (%s))' % sd, 'K_S2RTfun (%s, s2rt_int)' % sc.lst('s2rtlst', ['s2rt_bool', 'K_S2RTbas (K_S2RTBASdef (%s))' % sd]),
                    'K_S2RTtup (%s)' % sc.lst('s2rtlst', ['s2rt_int', 's2rt_addr']), 'K_S2RTbas (K_S2RTBASimp (1, mksymname ("imp")))', 's2rt_type',
                    'K_S2RTerr ()', 'K_S2RTVar (%s)' % sv, 'K_S2RTVar (%s)' % sv2):
            js(sc, 'jsonize_s2rt', [srt])
        js(sc, 'jsonize_s2rtlst', [sc.lst('s2rtlst', ['K_S2RTerr ()', 'K_S2RTVar (%s)' % sv])])
        # the records of the sorts: stamps and external names
        for kd in ('K_TYRECKINDflt1 (mkstamp (0))', 'K_TYRECKINDflt_ext ("ext")'):
            kv = sc.val(kd, 'tyreckind'); js(sc, 'jsonize_tyreckind', [kv])
        lab = sc.lst('labs2explst', ['K_labs2exp (mklab (0), OS_stringopt ("nm"), %s)' % S(sc, 's2exp', 1), 'K_labs2exp (mklab (1), ON_stringopt (), %s)' % S(sc, 's2exp', 1)])
        js(sc, 'jsonize_labs2explst', ['0', lab]); js(sc, 'jsonize_labs2explst', ['1', lab])
        sc.say('-- cells')
        for c in sc.pool.get('s2cst', []):
            sc.do('s2cst_set_extdef (%s, mkscstextdef (%d))' % (c, R.randint(0, 3)))
            if R.random() < 0.6: sc.do('s2cst_add_supcls (%s, %s)' % (c, S(sc, 's2exp', 1)))
            if R.random() < 0.5: sc.do('s2cst_set_dconlst (%s, OS_d2conlstopt (%s))' % (c, sc.lst('d2conlst', [sc.handle('d2con', 0.3) for _ in range(R.choice([0, 1, 2]))])))
            js(sc, 'jsonize_s2cst', [c]); js(sc, 'jsonize_s2cst_long', [c])
        js(sc, 'jsonize_s2cstlst', [sc.lst('s2cstlst', list(sc.pool.get('s2cst', [])))])
        js(sc, 'jsonize_s2rtdat_long', [sd])
        for v in sc.pool.get('s2var', []):
            js(sc, 'jsonize_s2var', [v]); js(sc, 'jsonize_s2var_long', [v])
        js(sc, 'jsonize_s2varlst', [sc.lst('s2varlst', list(sc.pool.get('s2var', [])))])
        for v in sc.pool.get('s2Var', []):
            if R.random() < 0.5: sc.do('s2Var_set_szexp (%s, %s)' % (v, S(sc, 's2zexp', 1)))
            js(sc, 'jsonize_s2Var', [v]); js(sc, 'jsonize_s2Var_long', [v])
        for c in sc.pool.get('d2con', []):
            js(sc, 'jsonize_d2con', [c]); js(sc, 'jsonize_d2con_long', [c])
        js(sc, 'jsonize_d2conlst', [sc.lst('d2conlst', list(sc.pool.get('d2con', [])))])
        sc.say('-- expressions')
        for _ in range(2): js(sc, 'jsonize_tyreckind', [S(sc, 'tyreckind', 1)])
        sc.fulls2 = False
        for _ in range(4):
            e = S(sc, 's2exp', 3)
            for f in ('jsonize0_s2exp', 'jsonize1_s2exp'): js(sc, f, [e])
            js(sc, 'jsonize_s2exp', [str(R.choice([0, 1])), e])
        for _ in range(2):
            es = S(sc, 's2explst', 2)
            js(sc, 'jsonize0_s2explst', [es]); js(sc, 'jsonize1_s2explst', [es]); js(sc, 'jsonize_s2explst', [str(R.choice([0, 1])), es])
            o = S(sc, 's2expopt', 2)
            js(sc, 'jsonize0_s2expopt', [o]); js(sc, 'jsonize1_s2expopt', [o]); js(sc, 'jsonize_s2expopt', [str(R.choice([0, 1])), o])
        js(sc, 'jsonize_labs2explst', [str(R.choice([0, 1])), S(sc, 'labs2explst', 2)])
        js(sc, 'jsonize_wths2explst', [str(R.choice([0, 1])), S(sc, 'wths2explst', 2)])
        js(sc, 'jsonize_s2eff', [S(sc, 's2eff', 1)])
        for _ in range(3): js(sc, 'jsonize_s2zexp', [S(sc, 's2zexp', 2)])
        # every constructor of s2exp (the printed form is the one of jsonize0: no hnfize)
        sc.fulls2 = True
        for _ in range(4):
            e = S(sc, 's2exp', 3)
            js(sc, 'jsonize0_s2exp', [e]); js(sc, 'jsonize_s2exp', ['0', e])
        sc.fulls2 = False
        flush(sc)
    F.append(('static', fam_static, 12))

    # ----------------------------------------------------------------------------------------------------------
    # the dynamics: cells, items, declarations (the expressions and patterns are reached through the declarations)
    def fam_dynamic(sc, k):
        R = sc.R
        sc.pools()
        sc.fulls2 = bool(k % 2)
        sc.say('-- cells')
        for c in sc.pool.get('d2cst', []): js(sc, 'jsonize_d2cst', [c]); js(sc, 'jsonize_d2cst_long', [c])
        for _ in range(2): sc.new('d2cst')
        for c in sc.pool.get('d2cst', []): js(sc, 'jsonize_d2cst', [c]); js(sc, 'jsonize_d2cst_long', [c])
        js(sc, 'jsonize_d2cstlst', [sc.lst('d2cstlst', list(sc.pool.get('d2cst', [])))])
        for v in sc.pool.get('d2var', []): js(sc, 'jsonize_d2var', [v]); js(sc, 'jsonize_d2var_long', [v])
        sc.say('-- items')
        for _ in range(8): js(sc, 'jsonize_d2itm', [S(sc, 'd2itm', 2)])
        sc.say('-- declarations')
        for _ in range(R.randint(4, 8)):
            js(sc, 'jsonize_d2ecl', [S(sc, 'd2ecl', R.randint(2, 4))])
        js(sc, 'jsonize_d2eclist', [S(sc, 'd2eclist', 3)])
        flush(sc)
    F.append(('dynamic', fam_dynamic, 40))

    # the expressions: every constructor of d2exp_node and p2at_node as the definition of a declaration
    def fam_exps(sc, k):
        R = sc.R
        sc.pools()
        sc.fulls2 = False
        L = sc.leaf('location')
        cs = [c for c, ts in G.types['d2exp_node']]
        for c in cs:
            if c in ('D2Emacsyn', 'D2Efix') and R.random() < 0.0: continue
            node = sc.datatype_con('d2exp_node', c, 4 if k % 2 else 3)
            e = sc.val('K_d2exp (%s, %s)' % (L, node), 'd2exp')
            d2c = 'K_d2ecl (%s, K_D2Cextvar ("n", %s))' % (L, e)
            js(sc, 'jsonize_d2ecl', [d2c])
        for c, ts in G.types['p2at_node']:
            node = sc.datatype_con('p2at_node', c, 4 if k % 2 else 3)
            p = 'K_p2at (%s, t_svs_nil (), t_dvs_nil (), ON_s2expopt (), %s)' % (L, node)
            v = sc.val('K_v2aldec (%s, %s, %s, ON_s2expopt ())' % (L, p, sc.val('K_d2exp (%s, K_D2Eempty ())' % L, 'd2exp')), 'v2aldec')
            js(sc, 'jsonize_d2ecl', ['K_d2ecl (%s, K_D2Cvaldecs (%s, %s))' % (L, sc.leaf('valkind'), sc.lst('v2aldeclst', [v]))])
        flush(sc)
    F.append(('exps', fam_exps, 8))

    # --jsonize-2: the output of a whole list of declarations
    def fam_out(sc, k):
        R = sc.R
        sc.pools()
        sc.fulls2 = bool(k % 2)
        sc.do('d2eclist_jsonize_out (dd_out, %s)' % S(sc, 'd2eclist', R.randint(2, 4)))
        flush(sc)
    F.append(('out', fam_out, 15))
    return [SETUP] + F

# ---------------------------------------------------------------------------------------------------------------------
def main(G, C, d3order):
    import t3_cases
    d = G.d
    Sc3 = t3_cases.build(G, C)
    F = families(G, C, Sc3, d)
    R = random.Random(SEED)
    scs = []
    for name, fam, n in F:
        for i in range(max(1, int(round(n * SCALE))) if n > 0 else 1):
            sc = Sc3(G, R, 'sc_%s_%d' % (name, i))
            fam(sc, i)
            scs.append(sc)
    chunks = []; cur = []; size = 0
    for sc in scs:
        t = t3_cases.wrap_text(sc.text())
        cur.append((sc.name, t)); size += t.count('\n')
        if size > 1500 or sc.name.startswith('sc_setup'):
            chunks.append(cur); cur = []; size = 0
    if cur: chunks.append(cur)
    bodies = []
    for ch in chunks:
        k = len(bodies)
        body = ''.join(t for n, t in ch)
        body += 'fun tc%d_body (): void = {\n' % k + ''.join('  val () = %s ()\n' % n for n, t in ch) + '}\n'
        bodies.append(body)
    chunk_files(d, C, bodies)
    print('j2_cases: %d scenarios, %d chunks, %d lines' % (len(scs), len(bodies), sum(b.count('\n') for b in bodies)))
