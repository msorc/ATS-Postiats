#!/usr/bin/env python3
"""hs_gen.py: the generator of the test of pats_histaexp (test/hs, see ../../PORTING.md "Typerase trees (histaexp)").
From ../../pats_histaexp.spec it writes
  hs_compat2.hats / hs_compat1.hats   the ATS2 / ATS1 layers: the constructors K_x, the list constructors LN_/LC_, the complete dumpers dd_x
  hs_cases.hats                       the cases, written once for ATS1 and ATS2 (the common subset): random trees built with the smart
                                      constructors of pats_histaexp.sats and with the raw constructors
usage: python3 hs_gen.py [SEED [COUNT]]"""
import re, random, sys, os
d = os.path.dirname(os.path.abspath(__file__))

def load_spec():
    recs = {}; cons = []; cur = None
    for l in open(os.path.join(d, '..', '..', 'pats_histaexp.spec')).read().split('\n'):
        l = l.split('#', 1)[0].rstrip()
        m = re.match(r'^record\s+(\w+)\s*\((.*)\)\s*$', l)
        if m:
            recs[m.group(1)] = [tuple(p.strip() for p in x.split(':', 1)) for x in m.group(2).split(',')]
            continue
        m = re.match(r'^type\s+(\w+)\s*$', l)
        if m: cur = m.group(1); continue
        m = re.match(r'^\s+(\w+)\s*\((.*)\)\s*$', l)
        if m and cur:
            cons.append((m.group(1), [a.strip() for a in m.group(2).split(',')] if m.group(2).strip() else []))
    return recs, cons

LEAF = {'int': 'dd_int', 'string': 'dd_string', 's2cst': 'dd_s2cst', 'symbol': 'dd_symbol', 'funclo': 'dd_funclo', 's2explst': 'dd_s2explst',
        'tyreckind': 'dd_tyreckind', 'd2con': 'dd_d2con', 's2var': 'dd_s2var', 'funlab': 'dd_funlab', 's2exp': 'dd_s2exp', 's2zexp': 'dd_s2zexp',
        'label': 'dd_label', 'stringopt': 'dd_stringopt', 'hitnam': 'dd_hitnam', 'hisexp': 'dd_hisexp', 'labhisexp': 'dd_labhisexp',
        'hisexplst': 'dd_hisexplst', 'hisexplstlst': 'dd_hisexplstlst', 'labhisexplst': 'dd_labhisexplst'}
LISTS = [('hisexplst', 'hisexp'), ('hisexplstlst', 'hisexplst'), ('labhisexplst', 'labhisexp'), ('s2explst', 's2exp'), ('s2rtlst', 's2rt')]

def compat(lang, cons):
    o = ['(* generated by hs_gen.py from pats_histaexp.spec: do not edit *)']
    # the constructors
    o.append('fun K_hitnam (a0: int, a1: int, a2: string): hitnam = ' + ('HITNAM (a0, a1, a2)' if lang == 1 else 'hitnam_new (a0, a1, a2)'))
    o.append('fun K_hisexp (a0: hitnam, a1: hisexp_node): hisexp = ' + ("'{hisexp_name= a0, hisexp_node= a1}" if lang == 1 else 'hisexp_new (a0, a1)'))
    o.append('fun K_labhisexp (a0: label, a1: stringopt, a2: hisexp): labhisexp = ' + ('HSLABELED (a0, a1, a2)' if lang == 1 else 'labhisexp_new (a0, a1, a2)'))
    for c, args in cons:
        ps = ', '.join('a%d: %s' % (i, t) for i, t in enumerate(args))
        call = ', '.join('a%d' % i for i in range(len(args)))
        o.append('fun K_%s (%s): hisexp_node = %s' % (c, ps, ('%s (%s)' % (c, call)) if lang == 1 else ('hisexp_node_%s (%s)' % (c, call))))
    for l, e in LISTS:
        if lang == 1:
            o.append('fun LN_%s (): %s = list_nil ()' % (l, l)); o.append('fun LC_%s (x: %s, xs: %s): %s = list_cons (x, xs)' % (l, e, l, l))
        else:
            o.append('fun LN_%s (): %s = glist_nil ((*void*))' % (l, l)); o.append('fun LC_%s (x: %s, xs: %s): %s = glist_cons (x, xs)' % (l, e, l, l))
    # the dumpers
    if lang == 1:
        o.append('fun dd_hitnam (x: hitnam): void = (case+ x of HITNAM (a, b, c) => (dd_ps "HITNAM("; dd_int a; dd_ps ", "; dd_int b; dd_ps ", "; dd_string c; dd_ps ")"))')
    else:
        o.append('fun dd_hitnam (x: hitnam): void = (dd_ps "HITNAM("; dd_int (x.hitnam_ptr ()); dd_ps ", "; dd_int (x.hitnam_fin ()); dd_ps ", "; dd_string (x.hitnam_name ()); dd_ps ")")')
    arms = []
    for c, args in cons:
        vs = ', '.join('a%d' % i for i in range(len(args)))
        parts = ['dd_ps "%s("' % c]
        for i, t in enumerate(args):
            if i: parts.append('dd_ps ", "')
            parts.append('%s (a%d)' % (LEAF[t], i))
        parts.append('dd_ps ")"')
        pat = '%s%s (%s)' % ('' if lang == 1 else '~', c, vs)
        arms.append('  | %s => (%s)' % (pat, '; '.join(parts)))
    scrut = 'x' if lang == 1 else 'hisexp_node_view (x)'
    if lang == 1:
        hname, hnode = 'x.hisexp_name', 'x.hisexp_node'
        lab = '(case+ x of HSLABELED (a0, a1, a2) => (dd_ps "labhisexp("; dd_label a0; dd_ps ", "; dd_stringopt a1; dd_ps ", "; dd_hisexp a2; dd_ps ")"))'
    else:
        hname, hnode = 'x.hisexp_name ()', 'x.hisexp_node ()'
        lab = '(dd_ps "labhisexp("; dd_label (x.labhisexp_lab ()); dd_ps ", "; dd_stringopt (x.labhisexp_opt ()); dd_ps ", "; dd_hisexp (x.labhisexp_elt ()); dd_ps ")")'
    o.append('fun dd_hisexp (x: hisexp): void = (dd_ps "hisexp("; dd_hitnam (%s); dd_ps ", "; dd_hisexp_node (%s); dd_ps ")")' % (hname, hnode))
    o.append('and dd_hisexp_node (x: hisexp_node): void = (\n  case+ %s of\n%s\n)' % (scrut, '\n'.join(arms)))
    o.append('and dd_labhisexp (x: labhisexp): void = %s' % lab)
    for l, e in LISTS[:3]:
        o.append('and dd_%s (xs: %s): void = (dd_ps "["; dd_%s_aux (xs, true); dd_ps "]")' % (l, l, l))
        if lang == 1:
            o.append('and dd_%s_aux (xs: %s, first: bool): void = (\n  case+ xs of\n  | list_cons (x, xs1) => ((if first then () else dd_ps ", "); dd_%s (x); dd_%s_aux (xs1, false))\n  | list_nil () => ()\n)' % (l, l, e, l))
        else:
            o.append('and dd_%s_aux (xs: %s, first: bool): void =\n  if glist_is_cons (xs) then ((if first then () else dd_ps ", "); dd_%s (glist_head<%s> (xs)); dd_%s_aux (glist_tail<%s> (xs), false))\n  else ()' % (l, l, e, e, l, e))
    return '\n'.join(o) + '\n'

