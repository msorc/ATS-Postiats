# the cases: the objects (OBJ) are defined in hs_objs.hats; here only expressions
class CG:
    def __init__(self, seed):
        self.r = random.Random(seed)
        self.ncst = 9; self.nvar = 6; self.ndcon = 3; self.nfl = 3
    def cst(self): return 'hs_c%d' % self.r.randrange(self.ncst)
    def cstfun(self): return 'hs_c%d' % self.r.randrange(4)
    def var(self): return 'hs_v%d' % self.r.randrange(self.nvar)
    def sym(self): return 'hs_sym (%d)' % self.r.randrange(8)
    def lab(self): return 'hs_lab (%d)' % self.r.randrange(5)
    def s2e(self, d=2):
        r = self.r; t = r.random()
        if d == 0 or t < 0.25: return r.choice(['s2exp_int (%d)' % r.randrange(5), 's2exp_cst (%s)' % self.cst(), 's2exp_var (%s)' % self.var(), 's2exp_var (%s)' % self.var()])
        if t < 0.6: return 's2exp_cstapp (%s, %s)' % (self.cstfun(), self.s2es(d - 1))
        return 's2exp_vararg (%s)' % self.s2e(d - 1)
    def s2es(self, d=1):
        n = self.r.randrange(3)
        e = 'LN_s2explst ()'
        for _ in range(n): e = 'LC_s2explst (%s, %s)' % (self.s2e(d), e)
        return e
    def s2ze(self):
        return 's2zexp_make_s2exp (%s)' % self.s2e(1)
    def funclo(self): return self.r.choice(['FUNCLOfun ()', 'FUNCLOclo (1)', 'FUNCLOclo (0)', 'FUNCLOclo (~1)'])
    def tyreckind(self): return self.r.choice(['hs_tk (0)', 'hs_tk (1)', 'hs_tk (2)', 'hs_tk (3)', 'hs_tk (4)'])
    def sort(self): return self.r.choice(['s2rt_int', 's2rt_bool', 's2rt_addr', 's2rt_type', 's2rt_t0ype', 's2rt_prop', 's2rt_view', 's2rt_vtype'])
    def lhs(self, d):
        n = self.r.randrange(4)
        e = 'LN_labhisexplst ()'
        for _ in range(n): e = 'LC_labhisexplst (%s, %s)' % (self.lh(d), e)
        return e
    def lh(self, d):
        return 'K_labhisexp (%s, %s, %s)' % (self.lab(), self.r.choice(['hs_none ()', 'hs_some ("nm")', 'hs_none ()']), self.hse(d))
    def hses(self, d):
        n = self.r.randrange(4)
        e = 'LN_hisexplst ()'
        for _ in range(n): e = 'LC_hisexplst (%s, %s)' % (self.hse(d), e)
        return e
    def hsess(self, d):
        n = self.r.randrange(3)
        e = 'LN_hisexplstlst ()'
        for _ in range(n): e = 'LC_hisexplstlst (%s, %s)' % (self.hses(max(d - 1, 0)), e)
        return e
    def hse(self, d=3):
        r = self.r; t = r.random()
        if d == 0 or t < 0.3:
            return r.choice(['hisexp_tybox', 'hisexp_typtr', 'hisexp_funptr', 'hisexp_cloptr', 'hisexp_clotyp', 'hisexp_arrptr', 'hisexp_datconptr',
                'hisexp_datcontyp', 'hisexp_exnconptr', 'hisexp_undefined', 'hisexp_int_t0ype ()', 'hisexp_bool_t0ype ()', 'hisexp_size_t0ype ()',
                'hisexp_void_t0ype ()', 'hisexp_void_t0ype ()', 'hisexp_cst (%s)' % self.cst(), 'hisexp_cst (hs_void_cst ())', 'hisexp_tyabs (%s)' % self.sym(),
                'hisexp_tyvar (%s)' % self.var(), 'hisexp_tyvar (%s)' % self.var(), 'hisexp_tyclo (hs_funlab (%d))' % r.randrange(self.nfl),
                'hisexp_vararg (%s)' % self.s2e(), 'hisexp_s2exp (%s)' % self.s2e(), 'hisexp_s2exp (s2exp_cst (hs_void_cst ()))', 'hisexp_s2zexp (%s)' % self.s2ze(),
                'hisexp_make_srt (%s)' % self.sort(), 'hisexp_make_srtsym (%s, %s)' % (self.sort(), self.sym())])
        d -= 1
        k = r.randrange(11)
        if k == 0: return 'hisexp_app (%s, %s)' % (self.hse(d), self.hses(d))
        if k == 1: return 'hisexp_fun (%s, %s, %s)' % (self.funclo(), self.hses(d), self.hse(d))
        if k == 2: return 'hisexp_extype ("ext%d", %s)' % (r.randrange(3), self.hsess(d))
        if k == 3: return 'hisexp_refarg (%d, %s)' % (r.randrange(2), self.hse(d))
        if k == 4: return 'hisexp_tyarr (%s, %s)' % (self.hse(d), self.s2es())
        if k == 5: return 'hisexp_tyrec (%s, %s)' % (self.tyreckind(), self.lhs(d))
        if k == 6: return 'hisexp_tyrecsin (%s)' % self.lh(d)
        if k == 7: return 'hisexp_tyrec2 (%s, %s)' % (self.tyreckind(), self.lhs(d))
        if k == 8: return 'hisexp_tysum (hs_d%d, %s)' % (r.randrange(self.ndcon), self.lhs(d))
        if k == 9:
            # raw constructors with arbitrary names
            nm = 'K_hitnam (%d, %d, "nm%d")' % (r.randrange(2), r.randrange(2), r.randrange(3))
            return 'K_hisexp (%s, %s)' % (nm, self.node(d))
        return 'hisexp_fun (%s, %s, %s)' % (self.funclo(), self.hses(d), r.choice(['hisexp_void_t0ype ()', self.hse(d)]))
    def node(self, d):
        r = self.r; k = r.randrange(6)
        if k == 0: return 'K_HSEtybox ()'
        if k == 1: return 'K_HSEcst (%s)' % self.cst()
        if k == 2: return 'K_HSEtyrecsin (%s)' % self.lh(d)
        if k == 3: return 'K_HSEtyvar (%s)' % self.var()
        if k == 4: return 'K_HSEtyarr (%s, %s)' % (self.hse(d), self.s2es())
        return 'K_HSEs2exp (%s)' % self.s2e()

def cases(seed, count):
    g = CG(seed)
    out = ['(* generated by hs_gen.py: do not edit *)']
    for i in range(count):
        out.append('fun hs_case_%d (): void = hs_all (%d, %s)' % (i, i, g.hse(3)))
    out.append('fun hs_cases (): void = (')
    out.append('  ' + ';\n  '.join('hs_case_%d ()' % i for i in range(count)))
    out.append(')')
    out.append('fun hs_run (): void = (hs_consts (); hs_cases (); dd_flush ())')
    return '\n'.join(out) + '\n'

if __name__ == '__main__':
    seed = int(sys.argv[1]) if len(sys.argv) > 1 else 1
    count = int(sys.argv[2]) if len(sys.argv) > 2 else 400
    recs, cons = load_spec()
    for lang in (1, 2):
        open(os.path.join(d, 'hs_compat%d.hats' % lang), 'w').write(compat(lang, cons))
    open(os.path.join(d, 'hs_cases.hats'), 'w').write(cases(seed, count))
    print('hs_gen: %d constructors, %d cases' % (len(cons), count))
