#!/usr/bin/env python3
# usage: python3 deepdump_gen.py   (rewrites deepdump1.hats and deepdump.hats)
#
# Generates, from ../pats_syntax.spec, a *complete* dumper of the level-0 syntax tree
# (every node, field and location) in ATS1 (deepdump1.hats, for pardump1.dats) and
# in ATS2 (deepdump.hats, for pardump.dats). fprint_d0ecl of pats_syntax_print.dats is
# coarse ("D0Cfundecs(...)"): the differential test of the parsers dumps the trees with
# these functions, one function [dd_T] per type T of the spec.
#
#   record R (f: T, ..)    ->  R{f=..,g=..}
#   type N, constructor C  ->  C(a,b)
#   glist(E) / gopt(E)     ->  [a,b] / - | some(a)
import re, os, sys

d = os.path.dirname(os.path.abspath(__file__))
spec = open(os.path.join(d, '..', 'pats_syntax.spec')).read().split('\n')

lists = {}   # alias -> elem
opts = {}    # alias -> elem
recs = {}    # name -> [(field, type)]
types = {}   # name -> [(ctor, [argtypes])]
order = []

def splitf(a):
    parts = []; dep = 0; b = ''
    for ch in a:
        if ch in '(': dep += 1
        if ch in ')': dep -= 1
        if ch == ',' and dep == 0: parts.append(b.strip()); b = ''; continue
        b += ch
    if b.strip(): parts.append(b.strip())
    return parts

cur = None
for l in spec:
    l = l.split('#', 1)[0].rstrip()
    if not l: continue
    m = re.match(r'^typedef\s+(\w+)\s*=\s*glist\((\w+)\)\s*$', l)
    if m: lists[m.group(1)] = m.group(2); continue
    m = re.match(r'^typedef\s+(\w+)\s*=\s*gopt\((\w+)\)\s*$', l)
    if m: opts[m.group(1)] = m.group(2); continue
    if l.startswith('typedef') or l.startswith('vtypedef'): continue
    m = re.match(r'^record\s+(\w+)\s*\((.*)\)\s*$', l)
    if m:
        recs[m.group(1)] = [tuple(p.split(':')) for p in splitf(m.group(2))]
        recs[m.group(1)] = [(a.strip(), b.strip()) for a, b in recs[m.group(1)]]
        order.append(m.group(1)); cur = None; continue
    m = re.match(r'^type\s+(\w+)\s*$', l)
    if m: cur = m.group(1); types[cur] = []; order.append(cur); continue
    m = re.match(r'^\s+(\w+)\s*\((.*)\)\s*$', l)
    if m and cur:
        types[cur].append((m.group(1), [p.strip() for p in splitf(m.group(2))])); continue
    raise Exception('spec line: ' + l)

# builtin aliases
lists['symbolist'] = 'symbol'
opts['symbolopt'] = 'symbol'
for t in ('i0nt', 'c0har', 'f0loat', 's0tring'): pass

LEAF = ['location', 'symbol', 'label', 'token', 'filename', 'int', 'bool', 'string',
        'funkind', 'valkind', 'srpifkind', 'cstsp', 'e0xpactkind', 'macsynkind', 'assoc', 'S0Ed2ctype',
        'i0nt', 'c0har', 'f0loat', 's0tring']
for t in LEAF:
    pass

def known(t):
    return t in recs or t in types or t in lists or t in opts or t in LEAF

for r, fs in recs.items():
    for f, t in fs:
        assert known(t), (r, f, t)
for n, cs in types.items():
    for c, ts in cs:
        for t in ts: assert known(t), (n, c, t)

# records of ATS2 that are one-constructor datatypes in ATS1
SPECIAL1 = {'labs0exp': 'SL0ABELED', 'labd0exp': 'DL0ABELED', 'datsdef': 'DATSDEF'}
# ---------------------------------------------------------------- ATS1
def gen1():
    o = []
    o.append('''(* generated by deepdump_gen.py: complete dumper of the level-0 tree (ATS1) *)
macdef dd_out = stdout_ref
fun dd_ps (s: string): void = fprint_string (dd_out, s)
fun dd_location (x: location): void = $LOC.fprint_location (dd_out, x)
fun dd_symbol (x: symbol): void = $SYM.fprint_symbol (dd_out, x)
fun dd_label (x: label): void = $LAB.fprint_label (dd_out, x)
fun dd_token (x: token): void = fprint_token (dd_out, x)
fun dd_i0nt (x: i0nt): void = fprint_token (dd_out, x)
fun dd_c0har (x: c0har): void = fprint_token (dd_out, x)
fun dd_f0loat (x: f0loat): void = fprint_token (dd_out, x)
fun dd_s0tring (x: s0tring): void = fprint_token (dd_out, x)
fun dd_filename (x: filename): void = $FIL.fprint_filename_full (dd_out, x)
fun dd_int (x: int): void = fprint_int (dd_out, x)
fun dd_bool (x: bool): void = fprint_bool (dd_out, x)
fun dd_string (x: string): void = (dd_ps "\\""; fprint_string (dd_out, x); dd_ps "\\"")
fun dd_funkind (x: funkind): void = fprint_funkind (dd_out, x)
fun dd_valkind (x: valkind): void = fprint_valkind (dd_out, x)
fun dd_srpifkind (x: srpifkind): void = case+ x of SRPIFKINDif () => dd_ps "if" | SRPIFKINDifdef () => dd_ps "ifdef" | SRPIFKINDifndef () => dd_ps "ifndef"
fun dd_cstsp (x: cstsp): void = fprint_cstsp (dd_out, x)
fun dd_e0xpactkind (x: e0xpactkind): void = fprint_e0xpactkind (dd_out, x)
fun dd_macsynkind (x: macsynkind): void = fprint_macsynkind (dd_out, x)
fun dd_assoc (x: assoc): void = case+ x of ASSOCnon () => dd_ps "ASSOCnon" | ASSOClft () => dd_ps "ASSOClft" | ASSOCrgt () => dd_ps "ASSOCrgt"
fun dd_S0Ed2ctype (x: S0Ed2ctype): void = dd_ps "S0Ed2ctype(...)"
''')
    names = list(order) + [n + '_node' for n in []]
    first = True
    def kw():
        nonlocal first
        k = 'fun' if first else 'and'
        first = False
        return k
    for n in order:
        if n in recs:
            fs = recs[n]
            body = ['dd_ps "%s{"' % n]
            for i, (f, t) in enumerate(fs):
                body.append('dd_ps "%s%s="' % (',' if i else '', f))
                body.append('dd_%s %s' % (t, ('f%d' % i) if n in SPECIAL1 else 'x.' + f))
            body.append('dd_ps "}"')
            if n in SPECIAL1:
                # ATS1: datatype sl0abeled / dl0abeled
                con = SPECIAL1[n]
                o.append('%s dd_%s (x: %s): void = case+ x of %s (%s) => (%s)\n' % (kw(), n, n, con, ', '.join('f%d' % i for i in range(len(fs))), '; '.join(body)))
            else:
                o.append('%s dd_%s (x: %s): void = (%s)\n' % (kw(), n, n, '; '.join(body)))
        else:
            arms = []
            for c, ts in types[n]:
                cc = 'D0Cextype' if c == 'D0Cextype2' else c
                vs = ['a%d' % i for i in range(len(ts))]
                pat = '%s (%s)' % (cc, ', '.join(vs)) if vs else '%s ()' % cc
                parts = ['dd_ps "%s("' % c]
                for i, (v, t) in enumerate(zip(vs, ts)):
                    if i: parts.append('dd_ps ","')
                    parts.append('dd_%s %s' % (t, v))
                parts.append('dd_ps ")"')
                arms.append('  | %s => (%s)' % (pat, '; '.join(parts)))
            o.append('%s dd_%s (x: %s): void = case+ x of\n%s\n' % (kw(), n, n, '\n'.join(arms)))
    for a, e in lists.items():
        if a == 'symbolist': pass
        o.append('%s dd_%s (xs: %s): void = (dd_ps "["; dd_%s_aux (xs, 0); dd_ps "]")\n' % (kw(), a, a, a))
        o.append('and dd_%s_aux (xs: %s, i: int): void = case+ xs of\n  | list_cons (x, xs1) => ((if i > 0 then dd_ps ","); dd_%s x; dd_%s_aux (xs1, i+1))\n  | list_nil () => ()\n' % (a, a, e, a))
    for a, e in opts.items():
        o.append('%s dd_%s (x: %s): void = case+ x of\n  | Some y => (dd_ps "some("; dd_%s y; dd_ps ")")\n  | None () => dd_ps "-"\n' % (kw(), a, a, e))
    return '\n'.join(o)

# ---------------------------------------------------------------- ATS2
def gen2():
    o = []
    o.append('''(* generated by deepdump_gen.py: complete dumper of the level-0 tree (ATS2) *)
macdef dd_out = stdout_ref
fn dd_ps (s: string): void = fprint_string (dd_out, s)
fn dd_location (x: location): void = $LOC.fprint_location (dd_out, x)
fn dd_symbol (x: symbol): void = $SYM.fprint_symbol (dd_out, x)
fn dd_label (x: label): void = $LAB.fprint_label (dd_out, x)
fn dd_token (x: token): void = fprint_token (dd_out, x)
fn dd_i0nt (x: i0nt): void = fprint_token (dd_out, x)
fn dd_c0har (x: c0har): void = fprint_token (dd_out, x)
fn dd_f0loat (x: f0loat): void = fprint_token (dd_out, x)
fn dd_s0tring (x: s0tring): void = fprint_token (dd_out, x)
fn dd_filename (x: filename): void = $FIL.fprint_filename_full (dd_out, x)
fn dd_int (x: int): void = fprint_int (dd_out, x)
fn dd_bool (x: bool): void = fprint_bool (dd_out, x)
fn dd_string (x: string): void = (dd_ps "\\""; fprint_string (dd_out, x); dd_ps "\\"")
fn dd_funkind (x: funkind): void = fprint_funkind (dd_out, x)
fn dd_valkind (x: valkind): void = fprint_valkind (dd_out, x)
fn dd_srpifkind (x: srpifkind): void = (case+ x of SRPIFKINDif () => dd_ps "if" | SRPIFKINDifdef () => dd_ps "ifdef" | SRPIFKINDifndef () => dd_ps "ifndef")
fn dd_cstsp (x: cstsp): void = fprint_cstsp (dd_out, x)
fn dd_e0xpactkind (x: e0xpactkind): void = fprint_e0xpactkind (dd_out, x)
fn dd_macsynkind (x: macsynkind): void = fprint_macsynkind (dd_out, x)
fn dd_assoc (x: assoc): void = (case+ x of ASSOCnon () => dd_ps "ASSOCnon" | ASSOClft () => dd_ps "ASSOClft" | ASSOCrgt () => dd_ps "ASSOCrgt")
fn dd_S0Ed2ctype (x: S0Ed2ctype): void = dd_ps "S0Ed2ctype(...)"
''')
    first = True
    def kw():
        nonlocal first
        k = 'fun' if first else 'and'
        first = False
        return k
    for n in order:
        if n in recs:
            fs = recs[n]
            body = ['dd_ps "%s{"' % n]
            for i, (f, t) in enumerate(fs):
                body.append('dd_ps "%s%s="' % (',' if i else '', f))
                body.append('dd_%s (x.%s())' % (t, f))
            body.append('dd_ps "}"')
            o.append('%s dd_%s (x: %s): void = (%s)\n' % (kw(), n, n, '; '.join(body)))
        else:
            arms = []
            for c, ts in types[n]:
                vs = ['a%d' % i for i in range(len(ts))]
                pat = '~%s (%s)' % (c, ', '.join(vs)) if vs else '~%s ()' % c
                parts = ['dd_ps "%s("' % c]
                for i, (v, t) in enumerate(zip(vs, ts)):
                    if i: parts.append('dd_ps ","')
                    parts.append('dd_%s (%s)' % (t, v))
                parts.append('dd_ps ")"')
                arms.append('  | %s => (%s)' % (pat, '; '.join(parts)))
            o.append('%s dd_%s (x: %s): void = case+ %s_view (x) of\n%s\n' % (kw(), n, n, n, '\n'.join(arms)))
    for a, e in lists.items():
        o.append('%s dd_%s (xs: %s): void = (dd_ps "["; dd_%s_aux (xs, 0); dd_ps "]")\n' % (kw(), a, a, a))
        o.append('and dd_%s_aux (xs: %s, i: int): void = case+ glist_view (xs) of\n  | ~GLcons (x, xs1) => ((if i > 0 then dd_ps ","); dd_%s (x); dd_%s_aux (xs1, i+1))\n  | ~GLnil () => ()\n' % (a, a, e, a))
    for a, e in opts.items():
        o.append('%s dd_%s (x: %s): void = case+ gopt_view (x) of\n  | ~GOsome (y) => (dd_ps "some("; dd_%s (y); dd_ps ")")\n  | ~GOnone () => dd_ps "-"\n' % (kw(), a, a, e))
    return '\n'.join(o)

open(os.path.join(d, 'deepdump1.hats'), 'w').write(gen1())
open(os.path.join(d, 'deepdump.hats'), 'w').write(gen2())
