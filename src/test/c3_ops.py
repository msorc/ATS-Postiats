def reg_gen():
    o = ['(* generated by c3_ops.py: the registers of the interpreter of the constraint-solver test *)']
    for i, (c, t) in enumerate(TYPES):
        o.append('#define T_%s %d' % (c, i))
        o.append('fun g_%s (i: int): %s = $UN.cast{%s} (c3_get (T_%s, i))' % (c, t, t, c))
        o.append('fun p_%s (i: int, x: %s): void = c3_put (T_%s, i, $UN.cast{ptr} (x))' % (c, t, c))
    for e, (lc, lt) in LISTS.items():
        o.append('fun rd_l%s_n (n: int): %s = if n <= 0 then LN_%s () else let val x = g_%s (c3_int ()) val xs = rd_l%s_n (n-1) in LC_%s (x, xs) end'
                 % (e, lt, lt, e, e, lt))
        o.append('fun rd_l%s (): %s = rd_l%s_n (c3_int ())' % (e, lt, e))
    o.append('fun srt_of (k: int): s2rt = (')
    for i, n in enumerate(SORTS):
        o.append('  if k = %d then %s else' % (i, s2_cases2.SORTN[n]))
    o.append('  s2rt_int')
    o.append(')')
    return '\n'.join(o) + '\n'

