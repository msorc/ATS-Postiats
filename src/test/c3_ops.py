def exec_gen():
    o = ['(* generated by c3_ops.py: the operations of the interpreter of the constraint-solver test *)']
    o.append('fun exec_op (opc: int): void =')
    o.append('  case+ opc of')
    names = {}
    for k, (name, args, body, kind) in enumerate(OPS):
        names[name] = k + 1
        o.append('  | %d => let (* %s *)' % (k + 1, name))
        for a in (args.split() if args else []):
            n, t = a.split(':')
            if t == 'i': o.append('      val %s = c3_int ()' % n)
            elif t == 's': o.append('      val %s = c3_str ()' % n)
            elif t[0] == 'w': o.append('      val %s = c3_int ()' % n)
            elif t[0] == 'r': o.append('      val %s = g_%s (c3_int ())' % (n, t[1:]))
            elif t[0] == 'l': o.append('      val %s = rd_l%s ()' % (n, t[1:]))
        if kind == 'env':
            o.append('      var env: s2vbcfenv = $UN.castvwtp0{s2vbcfenv} (c3_get_env ())')
            o.append('      val () = %s' % body.replace('\n', '\n      '))
            o.append('      val () = c3_put_env ($UN.castvwtp0{ptr} (env))')
            o.append('    in end')
        else:
            o.append('      val () = %s' % body.replace('\n', '\n      '))
            o.append('    in end')
    o.append('  | _ => (dd_ps "bad opcode "; dd_int (opc); dd_nl ())')
    return '\n'.join(o) + '\n', names

