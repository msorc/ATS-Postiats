# Test of the group C2 of the ccomp port: pats_ccomp_dynexp.dats, pats_ccomp_decl.dats, pats_ccomp_claulst.dats (ATS2) against the ATS1 build of the same three
# modules of src/ (see ../../PORTING.md, "ccomp group C2"). Same method as hd_gen.py / t3_gen.py: ONE generated program of scenarios, written in the common subset
# of ATS1 and ATS2, is compiled by the ATS2 driver (cc2dump.dats) and by the ATS1 driver (cc2dump1.dats, linked with the ATS1 objects of the main tree for the
# modules of the front end and for the THREE modules under test); the stdout and the stderr of the two must be identical.
#
# Everything else of ccomp (pats_ccomp.dats, _tmpvar, _funlab, _funent, _ccompenv, _instrseq, _hipat, _caseof, _trywith, ...) is a TEST DOUBLE written once for the
# two languages (the same text, modulo the representation of the cells: cc2_cells{1,2}.hats): the constructors of the trees are the smart constructors of
# the sats; the environment (the bindings, the tail-call frames, the sets of the function labels and of the environment variables) lives in cc2_state.c; the
# functions of the other groups (patterns, case, loops, ...) print their arguments and add a comment instruction. Every double that changes a global
# state prints a line "  | ..." so that the order of the calls, their arguments and the numbering of the temporaries and labels are compared too.
#  * cc2_hd_*.hats: the compat layers of hd_gen.py (K_<CON> wrappers and dumpers of the front-end trees), written here under other names
#  * cc2_compat{1,2}.hats: from ../../pats_ccomp.spec: K_<CON> wrappers, typed lists/options and COMPLETE dumpers cd_<T> of every type of the sats of ccomp
#  * cc2_cases_<k>.hats: the scenarios (cc2_cases.py): random erased trees, patterns, declarations and clause matrices
