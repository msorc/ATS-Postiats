# ---------------------------------------------------------------------------------------------------------------------------------- the spec of ccomp
CL = {}; CO = {}; CR = {}; CT = {}; CORDER = []; CMUT = {}
def load_cc(path):
    cur = None
    for l in open(path).read().split('\n'):
        l = l.split('#', 1)[0].rstrip()
        if not l: continue
        m = re.match(r'^typedef\s+(\w+)\s*=\s*glist\((\w+)\)\s*$', l)
        if m: CL[m.group(1)] = m.group(2); continue
        m = re.match(r'^typedef\s+(\w+)\s*=\s*gopt\((\w+)\)\s*$', l)
        if m: CO[m.group(1)] = m.group(2); continue
        if l.startswith('typedef') or l.startswith('vtypedef'): continue
        m = re.match(r'^record\s+(\w+)\s*\((.*)\)\s*$', l)
        if m:
            fs = []
            for p in G.splitf(m.group(2)):
                mm = re.match(r'^(mut\s+)?(\w+)\s*:\s*(.+)$', p)
                fs.append((mm.group(2), mm.group(3).strip()))
                if mm.group(1): CMUT.setdefault(m.group(1), []).append(mm.group(2))
            CR[m.group(1)] = fs; CORDER.append(m.group(1)); cur = None
            continue
        m = re.match(r'^type\s+(\w+)\s*$', l)
        if m:
            cur = m.group(1); CT[cur] = []; CORDER.append(cur); continue
        m = re.match(r'^\s+(\w+)\s*\((.*)\)\s*$', l)
        if m and cur:
            CT[cur].append((m.group(1), [p.strip() for p in G.splitf(m.group(2))])); continue
        raise Exception('spec line: ' + l)
load_cc(os.path.join(M, 'pats_ccomp.spec'))
# the records that are abstract in ATS1 (private records of the doubles: cc2_cells{1,2}.hats), dumped by hand
CCELLS = ['tmplab', 'tmpvar', 'd2env', 'funlab', 'funent']
# ATS1 shapes of the other records (one-constructor datatypes, flat tuples)
CONE1 = {'labprimval': 'LABPRIMVAL', 'hifundec2': 'HIFUNDEC2', 'hiimpdec2': 'HIIMPDEC2'}
CTUP1 = {'tmpmov': 2}
CATS1TYPE = {'tmpmov': '@(tmprimval, tmpvar)'}
CCT = set(CORDER) | set(CL) | set(CO)
LISTS1_ABSTRACT = ()   # ATS1: the early declarations of pats_ccomp.sats use the abstract ccomp_instrlst_type, the later ones List (instr): the files assume them equal

def ats1ty(t):
    return CATS1TYPE.get(t, t)

def ddname(t):
    if t in CCT: return 'cd_' + t
    return 'dd_' + t

# ---------------------------------------------------------------------------------------------------------------------------------- the compat layer of ccomp
def gen_cc_compat(lang):
    o = []
    o.append('(* generated by cc2_gen.py (%s): wrappers of the constructors of pats_ccomp.sats, typed lists/options, COMPLETE dumpers cd_<T> *)' % ('ATS1' if lang == 1 else 'ATS2'))
    for a, e in CL.items():
        if lang == 1 and a in LISTS1_ABSTRACT:
            o.append('fun LN_%s (): %s = $UN.cast{%s} (list_nil {ptr} ())' % (a, a, a))
            o.append('fun LC_%s (x: %s, xs: %s): %s = $UN.cast{%s} (list_cons ($UN.cast{ptr} (x), $UN.cast{List (ptr)} (xs)))' % (a, e, a, a, a))
        elif lang == 1:
            o.append('fun LN_%s (): %s = list_nil ()' % (a, a))
            o.append('fun LC_%s (x: %s, xs: %s): %s = list_cons (x, xs)' % (a, ats1ty(e), a, a))
        else:
            o.append('fun LN_%s (): %s = glist_nil ()' % (a, a))
            o.append('fun LC_%s (x: %s, xs: %s): %s = glist_cons<%s> (x, xs)' % (a, e, a, a, e))
    for a, e in CO.items():
        if lang == 1:
            o.append('fun ON_%s (): %s = None ()' % (a, a))
            o.append('fun OS_%s (x: %s): %s = Some (x)' % (a, ats1ty(e), a))
        else:
            o.append('fun ON_%s (): %s = gopt_none ()' % (a, a))
            o.append('fun OS_%s (x: %s): %s = gopt_some<%s> (x)' % (a, e, a, e))
    o.append('')
    for n in CORDER:
        if n in CR:
            if n in CCELLS: continue
            fs = CR[n]
            params = ', '.join('a%d: %s' % (i, ats1ty(t) if lang == 1 else t) for i, (f, t) in enumerate(fs))
            args = ', '.join('a%d' % i for i in range(len(fs)))
            if lang == 2:
                o.append('fun K_%s (%s): %s = %s_new (%s)' % (n, params, n, n, args))
            elif n in CONE1:
                o.append('fun K_%s (%s): %s = %s (%s)' % (n, params, n, CONE1[n], args))
            elif n in CTUP1:
                o.append('fun K_%s (%s): %s = @(%s)' % (n, params, ats1ty(n), args))
            else:
                o.append("fun K_%s (%s): %s = '{ %s }" % (n, params, n, ', '.join('%s= a%d' % (f, i) for i, (f, t) in enumerate(fs))))
        else:
            for c, ts in CT[n]:
                params = ', '.join('a%d: %s' % (i, ats1ty(t) if lang == 1 else t) for i, t in enumerate(ts))
                args = ', '.join('a%d' % i for i in range(len(ts)))
                if lang == 2:
                    o.append('fun K_%s (%s): %s = %s_%s (%s)' % (c, params, n, n, c, args))
                else:
                    o.append('fun K_%s (%s): %s = %s (%s)' % (c, params, n, c, args))
    o.append('')
    # forward declarations of the dumpers of the cells (defined in cc2_common.hats)
    for c in CCELLS:
        o.append('extern fun cd_%s (x: %s): void' % (c, c))
    o.append('')
    first = [True]
    def kw():
        k = 'fun' if first[0] else 'and'
        first[0] = False
        return k
    for n in CORDER:
        if n in CCELLS: continue
        if n in CR:
            fs = CR[n]
            body = ['dd_ps "%s{"' % n]
            for i, (f, t) in enumerate(fs):
                body.append('dd_ps "%s%s="' % (',' if i else '', f))
                if lang == 2:
                    body.append('%s (%s (x))' % (ddname(t), f))
                elif n in CONE1:
                    body.append('%s f%d' % (ddname(t), i))
                elif n in CTUP1:
                    body.append('%s (x.%d)' % (ddname(t), i))
                else:
                    body.append('%s (x.%s)' % (ddname(t), f))
            body.append('dd_ps "}"')
            if lang == 1 and n in CONE1:
                o.append('%s cd_%s (x: %s): void = case+ x of %s (%s) => (%s)\n' % (kw(), n, n, CONE1[n], ', '.join('f%d' % i for i in range(len(fs))), '; '.join(body)))
            else:
                o.append('%s cd_%s (x: %s): void = (%s)\n' % (kw(), n, ats1ty(n) if lang == 1 else n, '; '.join(body)))
        else:
            arms = []
            for c, ts in CT[n]:
                vs = ['a%d' % i for i in range(len(ts))]
                pat = ('~%s (%s)' if lang == 2 else '%s (%s)') % (c, ', '.join(vs))
                parts = ['dd_ps "%s("' % c]
                for i, (v, t) in enumerate(zip(vs, ts)):
                    if i: parts.append('dd_ps ","')
                    parts.append('%s (%s)' % (ddname(t), v))
                parts.append('dd_ps ")"')
                arms.append('  | %s => (%s)' % (pat, '; '.join(parts)))
            if lang == 1:
                o.append('%s cd_%s (x: %s): void = case+ x of\n%s\n' % (kw(), n, n, '\n'.join(arms)))
            else:
                o.append('%s cd_%s (x: %s): void = case+ %s_view (x) of\n%s\n' % (kw(), n, n, n, '\n'.join(arms)))
    for a, e in CL.items():
        o.append('%s cd_%s (xs: %s): void = (dd_ps "["; cd_%s_aux (xs, 0); dd_ps "]")\n' % (kw(), a, a, a))
        if lang == 1:
            o.append('and cd_%s_aux (xs: %s, i: int): void = case+ xs of\n  | list_cons (x, xs1) => ((if i > 0 then dd_ps ","); %s x; cd_%s_aux (xs1, i+1))\n  | list_nil () => ()\n' % (a, a, ddname(e), a)
                     if a not in LISTS1_ABSTRACT else
                     'and cd_%s_aux (xs: %s, i: int): void = case+ $UN.cast{List (instr)} (xs) of\n  | list_cons (x, xs1) => ((if i > 0 then dd_ps ","); %s x; cd_%s_aux ($UN.cast{%s} (xs1), i+1))\n  | list_nil () => ()\n' % (a, a, ddname(e), a, a))
        else:
            o.append('and cd_%s_aux (xs: %s, i: int): void = case+ glist_view (xs) of\n  | ~GLcons (x, xs1) => ((if i > 0 then dd_ps ","); %s (x); cd_%s_aux (xs1, i+1))\n  | ~GLnil () => ()\n' % (a, a, ddname(e), a))
    for a, e in CO.items():
        if lang == 1:
            o.append('and cd_%s (x: %s): void = case+ x of\n  | Some y => (dd_ps "some("; %s y; dd_ps ")")\n  | None () => dd_ps "-"\n' % (a, a, ddname(e)))
        else:
            o.append('and cd_%s (x: %s): void = case+ gopt_view (x) of\n  | ~GOsome (y) => (dd_ps "some("; %s (y); dd_ps ")")\n  | ~GOnone () => dd_ps "-"\n' % (a, a, ddname(e)))
    return '\n'.join(o)

# ---------------------------------------------------------------------------------------------------------------------------------- the cells of the doubles
def cell_fields(c):
    return CR[c]

def gen_cells(lang):
    """K_<cell> and the uniform accessors cl_<field> (x) / cl_set_<field> (x, v) of the five cells, in the representation of each language"""
    o = ['(* generated by cc2_gen.py (%s): the cells of the doubles (tmplab, tmpvar, d2env, funlab, funent) *)' % ('ATS1' if lang == 1 else 'ATS2')]
    if lang == 1:
        # private boxed records; a mutable field is a [ref]; the abstract types of the sats are assumed to them. A field whose type mentions a cell, an
        # instruction or a primitive value is a [ptr] (cast by the accessors): an [assume] that is (indirectly) recursive makes atsopt loop
        dep = set('tmpvar tmpvaropt tmpvarlst funlab funlabopt funlablst funlablstopt funent funentopt d2env d2envlst d2envlstopt instrlst vbindmap'.split())
        def fty(t): return 'ptr' if t in dep else ats1ty(t)
        def isdep(t): return t in dep
        for c in CCELLS:
            fs = cell_fields(c)
            fl = []
            for f, t in fs:
                if f in CMUT.get(c, []): fl.append('%s= ref (%s)' % (f, fty(t)))
                else: fl.append('%s= %s' % (f, fty(t)))
            o.append("typedef %s_rec = '{ %s }" % (c, ', '.join(fl)))
        for c, ab in (('tmplab', 'tmplab_type'), ('tmpvar', 'tmpvar_type'), ('d2env', 'd2env_type'), ('funlab', 'ccomp_funlab_type'), ('funent', 'funent_type')):
            o.append('assume %s = %s_rec' % (ab, c))
        for c in CCELLS:
            fs = cell_fields(c)
            params = ', '.join('a%d: %s' % (i, ats1ty(t)) for i, (f, t) in enumerate(fs))
            def v(i, f, t):
                x = ('$UN.cast{ptr} (a%d)' % i) if isdep(t) else ('a%d' % i)
                return '%s= %s' % (f, ('ref (%s)' % x) if f in CMUT.get(c, []) else x)
            vals = ', '.join(v(i, f, t) for i, (f, t) in enumerate(fs))
            o.append("fun K_%s (%s): %s = '{ %s }" % (c, params, c, vals))
            for f, t in fs:
                get = ('$UN.cast{%s} (%s)' if isdep(t) else '%s%s')
                if f in CMUT.get(c, []):
                    rd = '!(x.%s)' % f
                    o.append('fun cl_%s (x: %s): %s = %s' % (f, c, ats1ty(t), ('$UN.cast{%s} (%s)' % (ats1ty(t), rd)) if isdep(t) else rd))
                    o.append('fun cl_set_%s (x: %s, v: %s): void = !(x.%s) := %s' % (f, c, ats1ty(t), f, '$UN.cast{ptr} (v)' if isdep(t) else 'v'))
                else:
                    rd = 'x.%s' % f
                    o.append('fun cl_%s (x: %s): %s = %s' % (f, c, ats1ty(t), ('$UN.cast{%s} (%s)' % (ats1ty(t), rd)) if isdep(t) else rd))
    else:
        for c in CCELLS:
            fs = cell_fields(c)
            params = ', '.join('a%d: %s' % (i, t) for i, (f, t) in enumerate(fs))
            o.append('fun K_%s (%s): %s = %s_new (%s)' % (c, params, c, c, ', '.join('a%d' % i for i in range(len(fs)))))
            for f, t in fs:
                o.append('fun cl_%s (x: %s): %s = %s (x)' % (f, c, t, f))
                if f in CMUT.get(c, []):
                    o.append('fun cl_set_%s (x: %s, v: %s): void = set_%s (x, v)' % (f, c, t, f))
    return '\n'.join(o) + '\n'

