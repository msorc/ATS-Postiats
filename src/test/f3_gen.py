#!/usr/bin/env python3
# usage: python3 f3_gen.py   (rewrites f3dd.hats f3dd1.hats)
#
# The complete dumpers of the level-3 trees and constraints for the whole-file test of the type checker (f3dump.dats, ATS2; f3dump1.dats, ATS1;
# PORTING.md, "Level 3 integration"). From the specs of staexp2, dynexp2, dynexp3 and trans3_env (the generator t3_gen.py / d2_gen.py: every type, every
# constructor, every field, in ATS2 and ATS1) plus the cells of t2_gen.py (s2cst s2var s2Var s2rtdat s2hole d2con d2cst d2var d2mac: all the fields through the
# getters, the mutable ones at the time of the dump, stamps; in full the first time they are met and as NAME#STAMP afterwards). The filenv of a staload is
# dumped through its d3eclistopt the first time its file is met.
import re, os, sys
sys.dont_write_bytecode = True
d = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, d)
import d2_gen as G
import t3_gen, t2_gen

def cells(lang):
    s = t2_gen.cells(lang)
    # the filenv of a staload: the d3eclistopt (the d2eclist was checked by the level-2 test)
    i = s.index('and dd_filenv (x: filenv): void =')
    s = s[:i]
    o = []
    o.append('and dd_filenv (x: filenv): void =')
    o.append('  (dd_ps "filenv("; dd_filename (filenv_get_name x); dd_ps ";";')
    o.append('   (if t2dump_seen_str ($SYM.symbol_get_name ($FIL.filename_get_fullname (filenv_get_name x))) > 0 then dd_ps "<staloaded>"')
    o.append('    else dd_d3eclistopt (filenv_get_d3eclistopt x)); dd_ps ")")')
    o.append('')
    return s + '\n'.join(o)

def gen(lang):
    txt = t3_gen.gen_compat(lang)
    lines = [l for l in txt.split('\n') if not re.match(r'^fun (K_|LN_|LC_|ON_|OS_)', l)]
    return '(* generated by f3_gen.py (%s) *)\n' % ('ATS1' if lang == 1 else 'ATS2') + '\n'.join(lines) + '\n' + cells(lang)

if __name__ == '__main__':
    open(os.path.join(d, 'f3dd.hats'), 'w').write(gen(2))
    open(os.path.join(d, 'f3dd1.hats'), 'w').write(gen(1))
